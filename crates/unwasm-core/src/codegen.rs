//! Emitting Rust that compiles.
//!
//! The rule this backend is built around is that the output always builds. Not
//! "usually", and not "after you fix the three places it gave up" — a
//! decompiler whose output does not compile cannot be checked against the
//! module it came from, and an unchecked decompilation is a story about the
//! code rather than a reading of it.
//!
//! Three consequences run through everything below:
//!
//! - **Nothing is skipped.** An opcode with no lowering is an error from
//!   [`crate::module`], not a comment in the output.
//! - **Values that outlive an effect are named.** wasm's operand stack has no
//!   Rust equivalent, so a pushed value is either folded into its consumer (only
//!   when it is a constant, a local or a global read) or spilled to a `let`
//!   before anything can change what it would have read.
//! - **Structure is taken, not recovered.** wasm's `block`/`loop`/`if` nest, and
//!   Rust's labelled blocks and loops nest the same way. Every frame becomes
//!   `'bN: { .. }` or `'bN: loop { .. }`, and a `br` becomes `break 'bN` or
//!   `continue 'bN`. There is no control-flow graph in this file, because there
//!   is no control-flow graph in the input.
//!
//! What this level does *not* do is recover types, structs or the shadow stack:
//! linear memory stays a byte vector, and a C local that lived in it stays an
//! address. That is the next level's job, and it is only safe to attempt on top
//! of something already known to run.

