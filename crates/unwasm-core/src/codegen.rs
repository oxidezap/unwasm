/// Where an import comes from, for grouping a host skeleton.
///
/// The grouping is the point: 102 methods in one list is a wall, and the same
/// 102 split into "these are WASI", "these are the C++ runtime" and "these
/// forty are yours" is a plan. Only the last group needs anything invented.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum ImportGroup {
    Wasi,
    CxxRuntime,
    EmscriptenRuntime,
    Embind,
    Emval,
    Application,
}

impl ImportGroup {
    fn of(module: &str, field: &str) -> Self {
        if module == "wasi_snapshot_preview1" {
            Self::Wasi
        } else if field.starts_with("_embind_") {
            Self::Embind
        } else if field.starts_with("_emval_") {
            Self::Emval
        } else if field.starts_with("__cxa_")
            || field.starts_with("__syscall")
            || matches!(
                field,
                "abort" | "getentropy" | "__assert_fail" | "__resumeException"
            )
        {
            Self::CxxRuntime
        } else if field.starts_with("emscripten_") || field.starts_with("_emscripten_") {
            Self::EmscriptenRuntime
        } else {
            Self::Application
        }
    }

    fn heading(self) -> &'static str {
        match self {
            Self::Wasi => "WASI. A subset over an in-memory filesystem answers these.",
            Self::CxxRuntime => {
                "The C++ runtime and syscalls. `__cxa_throw` should call `rt::throw`,\n    // which is what the generated `invoke_*` trampolines catch."
            }
            Self::EmscriptenRuntime => "Emscripten's runtime.",
            Self::Embind => {
                "embind: the module registers its classes and functions through\n    // these at startup. What it registers is the high-level API it means to\n    // expose — the one thing in a stripped module that describes itself."
            }
            Self::Emval => "emval: handles to values on the host side.",
            Self::Application => {
                "The application's own callbacks. Nothing but the application can\n    // say what these should do."
            }
        }
    }
}

/// The same body, reaching its state through a lock.
///
/// A threaded module's host is shared between its threads, so the pieces live
/// behind a mutex. The bodies are otherwise identical, and rewriting them here
/// keeps one table of what each import does rather than two that drift.
///
/// A poisoned lock is taken anyway: the panic that poisoned it was a guest
/// trap, and refusing to answer afterwards would turn one thread's failure
/// into every other thread's.
fn through_a_lock(body: &str) -> String {
    let mut out = body.to_string();
    for field in ["wasi", "cxx", "emscripten", "embind"] {
        // Through a placeholder, because the locked form contains the text
        // being replaced: a second pass over `self.wasi.` would find the one
        // inside `self.wasi.lock()…` and lock it again.
        let held = format!("<{field}>");
        out = out.replace(&format!("&mut self.{field}"), &format!("&mut *{held}"));
        out = out.replace(&format!("self.{field}."), &format!("{held}."));
        out = out.replace(
            &held,
            &format!("self.{field}.lock().unwrap_or_else(|held| held.into_inner())"),
        );
    }
    out
}

/// Bytes as a Rust byte-string literal, wrapped so a line stays readable.
///
/// A `\` at the end of a line skips the newline *and every space after it*,
/// so a data byte that is a space immediately after a wrap has to be escaped
/// or it disappears. That cost 626 bytes of one segment of the VoIP module and
/// only showed up when the module was run.
fn byte_string(bytes: impl Iterator<Item = u8>) -> String {
    let mut out = String::from("b\"");
    let mut column = 0usize;
    let mut just_wrapped = false;
    for byte in bytes {
        let escaped = match byte {
            b'"' => "\\\"".to_string(),
            b'\\' => "\\\\".to_string(),
            b'\n' => "\\n".to_string(),
            b'\r' => "\\r".to_string(),
            b'\t' => "\\t".to_string(),
            // The one byte a line continuation would swallow.
            b' ' if just_wrapped => "\\x20".to_string(),
            0x20..=0x7E => (byte as char).to_string(),
            other => format!("\\x{other:02x}"),
        };
        just_wrapped = false;
        column += escaped.len();
        out.push_str(&escaped);
        if column >= 100 {
            out.push_str("\\\n    ");
            column = 0;
            just_wrapped = true;
        }
    }
    out.push('"');
    out
}

/// A wasm signature as a short string: the parameters, then `->`, then the
/// result. `i` is i32, `j` i64, `f` f32, `d` f64.
///
/// A host implementation is only emitted when this matches exactly. Emscripten
/// has changed the shape of these imports before — `fd_seek` took a split i64
/// once — and a body written for the other shape would not compile, or worse
/// would compile and read the wrong argument.
fn shape(ty: &crate::module::FuncType) -> String {
    let letter = |value: &ValType| match value {
        ValType::I32 => 'i',
        ValType::I64 => 'j',
        ValType::F32 => 'f',
        ValType::F64 => 'd',
    };
    let params: String = ty.params.iter().map(letter).collect();
    let results: String = ty.results.iter().map(letter).collect();
    format!("{params}->{results}")
}

/// The body for an import the host library already answers, if this is one.
///
/// Everything here is mechanical: it is the same for every module an
/// Emscripten toolchain produced, which is precisely why it is worth writing
/// once. Anything that is *not* mechanical stays a `todo!()` — the
/// application's own callbacks, and the ones no host can answer honestly, like
/// `emscripten_asm_const_int`, which runs a string of JavaScript the module
/// carries.
fn known_import(field: &str, ty: &crate::module::FuncType) -> Option<&'static str> {
    let shape = shape(ty);
    let body = match (field, shape.as_str()) {
        // ---- WASI
        ("fd_write", "iiii->i") => "self.wasi.fd_write(caller, p0, p1, p2, p3)",
        ("fd_read", "iiii->i") => "self.wasi.fd_read(caller, p0, p1, p2, p3)",
        ("fd_pread", "iiiji->i") => "self.wasi.fd_pread(caller, p0, p1, p2, p3, p4)",
        ("fd_pwrite", "iiiji->i") => "self.wasi.fd_pwrite(caller, p0, p1, p2, p3, p4)",
        ("fd_seek", "ijii->i") => "self.wasi.fd_seek(caller, p0, p1, p2, p3)",
        ("fd_sync", "i->i") => "self.wasi.fd_sync(p0)",
        ("fd_close", "i->i") => "self.wasi.fd_close(p0)",
        ("environ_sizes_get", "ii->i") => "self.wasi.environ_sizes_get(caller, p0, p1)",
        ("environ_get", "ii->i") => "self.wasi.environ_get(caller, p0, p1)",
        ("args_sizes_get", "ii->i") => "self.wasi.args_sizes_get(caller, p0, p1)",
        ("args_get", "ii->i") => "self.wasi.args_get(caller, p0, p1)",
        ("random_get", "ii->i") | ("getentropy", "ii->i") => "self.wasi.random_get(caller, p0, p1)",
        ("clock_time_get", "iji->i") => "self.wasi.clock_time_get(caller, p2)",
        ("proc_exit", "i->") | ("exit", "i->") => "runtime::exit(p0)",

        // ---- the C++ runtime
        ("__cxa_throw", "iii->") => "self.cxx.throw(p0, p1)",
        ("__cxa_begin_catch", "i->i") => "self.cxx.begin_catch(p0)",
        ("__cxa_end_catch", "->") => "self.cxx.end_catch()",
        ("__cxa_rethrow", "->") => "self.cxx.rethrow()",
        ("__resumeException", "i->") => "self.cxx.rethrow()",
        ("__cxa_uncaught_exceptions", "->i") => "self.cxx.uncaught()",
        // `__cxa_find_matching_catch_*` and `__cxa_get_exception_ptr` are
        // deliberately absent. They are not mechanical: the glue compares the
        // thrown type against each requested catch type — through the module's
        // own `__cxa_can_catch` — and returns an adjusted pointer for a base
        // class. Answering with the exception unconditionally selects the
        // wrong handler for `throw Derived; catch (Base&)` and hands the guest
        // the wrong address, which is worse than saying it is not written.
        // The type id *is* the answer: Emscripten's glue is `(type) => type`,
        // because the personality routine compares the value it gets back
        // against the same pointers the module's own tables hold.
        ("llvm_eh_typeid_for", "i->i") => "p0",
        ("__assert_fail", "iiii->") => "runtime::assert_fail(caller, p0, p1, p2, p3)",

        // ---- Emscripten's runtime
        ("emscripten_resize_heap", "i->i") => "runtime::Emscripten::resize_heap(caller, p0)",
        ("emscripten_get_heap_max", "->i") => "runtime::Emscripten::heap_max(caller)",
        ("emscripten_date_now", "->d") | ("emscripten_get_now", "->d") => {
            "self.wasi.now_milliseconds"
        }
        ("_emscripten_get_now_is_monotonic", "->i") => "1",
        // The clock, as C sees it. UTC throughout: the host supplies the time
        // and nothing reads the machine's timezone, so a run does not depend
        // on where it ran.
        ("_localtime_js", "ji->i") | ("_gmtime_js", "ji->i") => "runtime::write_tm(caller, p1, p0)",
        // Older builds return nothing from it.
        ("_localtime_js", "ji->") | ("_gmtime_js", "ji->") => {
            "let _ = runtime::write_tm(caller, p1, p0);"
        }
        ("_mktime_js", "i->j") => "runtime::mktime(caller, p0)",
        // `strftime` is specified by the standard rather than by the
        // application, so it is the same for every module — and the locale
        // argument of `strftime_l` selects nothing this answers differently.
        ("strftime", "iiii->i") => "runtime::strftime(caller, p0, p1, p2, p3)",
        ("strftime_l", "iiiii->i") => "runtime::strftime(caller, p0, p1, p2, p3)",
        ("_tzset_js", "iiii->") => "runtime::tzset(caller, p0, p1, p2, p3)",
        ("_tzset_js", "iii->") => "runtime::tzset(caller, p0, p1, p2, 0)",
        ("emscripten_num_logical_cores", "->i") => "self.emscripten.cores",
        ("emscripten_console_error", "i->") => {
            "self.emscripten.console_error(caller, &mut self.wasi, p0)"
        }
        ("emscripten_memcpy_js", "iii->") => "caller.memory.copy(p0, p1, p2)",
        ("emscripten_runtime_keepalive_push", "->") => "self.emscripten.keepalive += 1",
        ("emscripten_runtime_keepalive_pop", "->") => "self.emscripten.keepalive -= 1",
        ("emscripten_async_call", "iii->") => "self.emscripten.scheduled.push((p0, p1, p2))",
        ("emscripten_exit_with_live_runtime", "->") => {
            "self.emscripten.exited_with_live_runtime = true"
        }
        ("emscripten_check_blocking_allowed", "->") => "()",
        // The thread bookkeeping the glue does for *its* workers, which this
        // model does not have. Each is a no-op here for a reason that is in
        // the glue itself rather than in a guess:
        //
        // `_emscripten_thread_cleanup` returns a Worker to the pool so it can
        // be reused; an OS thread that has returned needs nothing.
        // `_emscripten_thread_set_strongref` keeps a JavaScript reference to a
        // Worker alive; there is no such reference here.
        // `_emscripten_thread_mailbox_await` does nothing at all in the glue
        // when `Atomics.waitAsync` is unavailable — the comment there says so
        // — and that is the branch this is.
        ("_emscripten_thread_cleanup", "i->")
        | ("_emscripten_thread_set_strongref", "i->")
        | ("_emscripten_thread_mailbox_await", "i->") => "()",
        ("abort", "->") => "rt::trap(\"the module called abort\")",

        // ---- the syscalls that are honest over an in-memory filesystem
        ("__syscall_openat", "iiii->i") => "self.wasi.openat_at(caller, p1, p2)",
        ("__syscall_unlinkat", "iii->i") => "self.wasi.unlinkat(caller, p1)",
        // Nothing here is a terminal, and saying so is an answer rather than a
        // guess.
        ("__syscall_ioctl", "iii->i") => "-runtime::errno::NOTTY",
        // The struct layout is Emscripten's own rather than a guess — see
        // `Wasi::write_stat` — which is what makes these answerable at all.
        ("__syscall_stat64", "ii->i") | ("__syscall_lstat64", "ii->i") => {
            "self.wasi.stat_path(caller, p0, p1)"
        }
        ("__syscall_fstat64", "ii->i") => "self.wasi.stat_fd(caller, p0, p1)",
        // `newfstatat(dirfd, path, buf, flags)`: a relative path is resolved
        // against the working directory, so the descriptor decides nothing.
        ("__syscall_newfstatat", "iiii->i") => "self.wasi.stat_path(caller, p1, p2)",
        ("__syscall_chdir", "i->i") => "self.wasi.chdir(caller, p0)",
        ("__syscall_mkdirat", "iii->i") => "self.wasi.mkdirat(caller, p1)",
        ("__syscall_getdents64", "iii->i") => "self.wasi.getdents64(caller, p0, p1, p2)",
        ("__syscall_ftruncate64", "ij->i") => "self.wasi.ftruncate(p0, p1)",
        ("__syscall_fcntl64", "iii->i") => "self.wasi.fcntl(p0, p1, p2)",

        // ---- embind and emval
        ("_emval_incref", "i->") => "self.embind.incref(p0)",
        ("_emval_decref", "i->") => "self.embind.decref(p0)",
        ("_emval_take_value", "ii->i") => "self.embind.take_value()",
        _ => return None,
    };
    Some(body)
}

/// The body for an `_embind_register_*` call, which records rather than acts.
///
/// The argument carrying the name comes from the same table the static reader
/// uses, so what a run reports and what `unwasm inspect` claims cannot drift
/// apart.
fn known_registration(field: &str, ty: &crate::module::FuncType) -> Option<String> {
    let kind = field.strip_prefix("_embind_register_")?;
    let Some(at) = analysis::EMBIND_NAME_ARGUMENT
        .iter()
        .find(|(name, _)| *name == field)
        .map(|(_, at)| *at)
    else {
        // A registration that carries no name — a constructor is the one that
        // matters — is still worth recording: what a class registers, and in
        // which order, is the shape of its API.
        let arguments: Vec<String> = ty
            .params
            .iter()
            .enumerate()
            .filter(|(_, param)| **param == ValType::I32)
            .map(|(index, _)| format!("p{index}"))
            .collect();
        return Some(format!(
            "self.embind.register_unnamed(\"{kind}\", &[{}])",
            arguments.join(", ")
        ));
    };
    // Every registration takes its name as an i32 address, and the ones that
    // do not are not this.
    if ty.params.get(at) != Some(&ValType::I32) {
        return None;
    }
    // The i64 arguments of `_embind_register_bigint` are its bounds, not
    // anything a reader looks up, and they do not fit an i32 list.
    let rest: Vec<String> = ty
        .params
        .iter()
        .enumerate()
        .filter(|(index, param)| *index != at && **param == ValType::I32)
        .map(|(index, _)| format!("p{index}"))
        .collect();
    Some(format!(
        "self.embind.register(caller, \"{kind}\", p{at}, &[{}])",
        rest.join(", ")
    ))
}

/// Generates a host skeleton: an `impl Imports` with every method the module
/// still needs, grouped by where it comes from.
///
/// Every body is `todo!()` naming the import. That is deliberate: a skeleton
/// that returned zero would compile, run, and be wrong, and the module could
/// not tell the difference between "not written yet" and "answered 0". A
/// `todo!()` fails loudly at exactly the call that needs writing.
///
/// # Errors
///
/// As [`generate`].
pub fn generate_host(module: &Module) -> Result<String> {
    generate_host_with(module, false)
}

/// Generates a host skeleton, optionally answering the rest with defaults.
///
/// With `defaults`, an import nothing here can answer returns the zero of its
/// result type and records that it did, rather than stopping the run. The rule
/// this bends is the project's own — a stub returning zero is a hypothesis —
/// and it bends it in the one way that keeps it honest: the hypothesis is
/// counted, its first arguments are kept, and `Host::unanswered.report()`
/// prints the list a result has to be read against.
///
/// It is for reaching a path, not for studying one. A run that got somewhere
/// interesting under forty invented answers has to be repeated with the ones
/// that mattered answered properly.
///
/// # Errors
///
/// As [`generate`].
pub fn generate_host_with(module: &Module, defaults: bool) -> Result<String> {
    let analysis = analysis::analyse(module);
    // A threaded module hands its imports the memory every thread shares, and
    // a host written for the other one would be reading a memory the guest is
    // not using.
    let caller = if module.memory.as_ref().is_some_and(|memory| memory.shared) {
        "rt::Caller<'_, rt::SharedMemory>"
    } else {
        "rt::Caller<'_>"
    };
    let mut out = String::new();
    out.push_str(concat!(
        "// A host skeleton, generated by unwasm. Edit freely: this is a starting
",
        "// point, not something to regenerate over.
",
        "//
",
        "// The mechanical imports are implemented: WASI over an in-memory
",
        "// filesystem, the C++ runtime's exception entry points, Emscripten's own
",
        "// runtime, and embind's registrations, which are recorded. What is left
",
        "// as `todo!()` is what no host can answer for you — the application's own
",
        "// callbacks, and the ones that run JavaScript the module carries.
",
        "//
",
        "// A `todo!()` rather than a stub returning zero: a stub that returns zero
",
        "// compiles, runs, and is wrong, and the module cannot tell it apart from
",
        "// an answer.

",
        "use crate::generated::{self, rt, Imports};

",
    ));
    // The library, embedded rather than depended on, exactly as the runtime is.
    out.push_str("/// The mechanical half of a host. Regenerate rather than edit.\n");
    out.push_str("#[allow(dead_code)]\npub mod runtime {\n");
    for line in strip_tests(include_str!("hostlib.rs")).lines() {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "    {line}");
        }
    }
    out.push_str("}\n\n");
    let threaded = analysis.spawn.is_some();
    if threaded {
        out.push_str(concat!(
            "/// State the host needs, behind a lock because this module creates\n",
            "/// threads.\n",
            "///\n",
            "/// Every thread is another instance over the same memory and gets a clone\n",
            "/// of this — so the pieces are `Arc<Mutex<_>>` rather than owned: a file\n",
            "/// one thread writes has to be a file the others can read, and a copy per\n",
            "/// thread would be four filesystems that agree about nothing.\n",
            "#[derive(Debug, Default, Clone)]\n",
            "pub struct Host {\n",
            "    /// WASI, and the filesystem it reads.\n",
            "    pub wasi: std::sync::Arc<std::sync::Mutex<runtime::Wasi>>,\n",
            "    /// Exceptions in flight.\n",
            "    pub cxx: std::sync::Arc<std::sync::Mutex<runtime::Cxx>>,\n",
            "    /// Emscripten's runtime state.\n",
            "    pub emscripten: std::sync::Arc<std::sync::Mutex<runtime::Emscripten>>,\n",
            "    /// What embind registered, and what emval is holding.\n",
            "    pub embind: std::sync::Arc<std::sync::Mutex<runtime::Embind>>,\n",
            "    /// Imports answered with a default rather than an answer.\n",
            "    pub unanswered: std::sync::Arc<std::sync::Mutex<runtime::Unanswered>>,\n",
            "}\n\n",
        ));
    } else {
        out.push_str(concat!(
            "/// State the host needs. The four pieces the library answers with, and\n",
            "/// room for whatever the application's own imports need.\n",
            "#[derive(Debug, Default)]\n",
            "pub struct Host {\n",
            "    /// WASI, and the filesystem it reads.\n    pub wasi: runtime::Wasi,\n",
            "    /// Exceptions in flight.\n    pub cxx: runtime::Cxx,\n",
            "    /// Emscripten's runtime state.\n    pub emscripten: runtime::Emscripten,\n",
            "    /// What embind registered, and what emval is holding.\n",
            "    pub embind: runtime::Embind,\n",
            "    /// Imports answered with a default rather than an answer.\n",
            "    pub unanswered: runtime::Unanswered,\n",
            "}\n\n",
        ));
    }

    let mut grouped: std::collections::BTreeMap<ImportGroup, Vec<usize>> = Default::default();
    for (index, import) in module.func_imports.iter().enumerate() {
        // The trampolines are generated; they are not the host's to write.
        // Neither is `__pthread_create_js`, which has to reach back into the
        // instance and so cannot be a host method at all.
        if analysis
            .invokes
            .iter()
            .any(|invoke| invoke.import == index as u32)
            || analysis
                .spawn
                .is_some_and(|spawn| spawn.import == index as u32)
            || analysis
                .init_main_thread
                .is_some_and(|init| init.import == index as u32)
        {
            continue;
        }
        grouped
            .entry(ImportGroup::of(&import.module, &import.field))
            .or_default()
            .push(index);
    }

    let total: usize = grouped.values().map(Vec::len).sum();
    let answered = grouped
        .values()
        .flatten()
        .filter(|index| {
            let import = &module.func_imports[**index];
            module
                .types
                .get(import.type_index as usize)
                .is_some_and(|ty| {
                    known_import(&import.field, ty).is_some()
                        || known_registration(&import.field, ty).is_some()
                })
        })
        .count();
    let _ = writeln!(
        out,
        "// A `todo!()` body uses none of its arguments, and a skeleton that\n// warned about every one of them would bury the compiler output a reader\n// needs. The names stay, because they are what you fill the body in with.\n#[allow(unused_variables)]\nimpl Imports for Host {{\n    // {total} methods, {answered} of them answered by the library above\n    // and {} left for you. {} of the module's {} imports are Emscripten\n    // exception trampolines and are generated, so they are not here.",
        total - answered,
        analysis.invokes.len(),
        module.func_imports.len()
    );

    for (group, indices) in grouped {
        let _ = writeln!(out, "\n    // ---- {}", group.heading());
        for index in indices {
            let import = &module.func_imports[index];
            let ty = module.types.get(import.type_index as usize);
            let signature = ty.map_or_else(String::new, signature_of);
            let result = ty.map_or_else(String::new, return_type);
            let body = ty.and_then(|ty| {
                known_import(&import.field, ty)
                    .map(str::to_string)
                    .or_else(|| known_registration(&import.field, ty))
            });
            let body = body.map(|body| {
                if threaded {
                    through_a_lock(&body)
                } else {
                    body
                }
            });
            let (name, body) = match body {
                Some(body) => ("caller", body),
                // Answering with the zero of the type, and recording that it
                // did: the hypothesis is not hidden, it is counted.
                None if defaults => {
                    // The record is a list of i64, and a float is kept as its
                    // bits: the argument the guest passed is what a reader
                    // wants back, and a cast would round it.
                    let arguments: Vec<String> = ty
                        .map(|ty| {
                            ty.params
                                .iter()
                                .enumerate()
                                .map(|(at, param)| match param {
                                    ValType::I32 => format!("i64::from(p{at})"),
                                    ValType::I64 => format!("p{at}"),
                                    ValType::F32 => format!("i64::from(p{at}.to_bits())"),
                                    ValType::F64 => format!("p{at}.to_bits() as i64"),
                                })
                                .collect()
                        })
                        .unwrap_or_default();
                    let lock = if threaded {
                        ".lock().unwrap_or_else(|held| held.into_inner())"
                    } else {
                        ""
                    };
                    let record = format!(
                        "self.unanswered{lock}.record(\"{}::{}\", &[{}]);",
                        import.module,
                        import.field,
                        arguments.join(", ")
                    );
                    let zero = ty
                        .and_then(|ty| ty.results.first().map(|result| result.zero().to_string()))
                        .unwrap_or_default();
                    let body = if zero.is_empty() {
                        record
                    } else {
                        format!("{record}\n        {zero}")
                    };
                    ("_caller", body)
                }
                None => (
                    "_caller",
                    format!("todo!(\"{}::{}\")", import.module, import.field),
                ),
            };
            let _ = writeln!(
                out,
                "\n    fn {}(&mut self, {name}: &mut {caller}{signature}) {result} {{\n        {body}\n    }}",
                import_ident(import.module.as_str(), import.field.as_str()),
            );
        }
    }
    out.push_str(
        "}
",
    );
    Ok(out)
}

/// Generates a single Rust file from a decoded wasm module.
///
/// # Errors
///
/// Returns [`Error::Unsupported`] for a construct with no faithful Rust form,
/// and [`Error::Invalid`] if the module's own indices do not line up.
pub fn generate(module: &Module) -> Result<String> {
    let mut files = generate_files(module, Layout::Single)?;
    Ok(files.remove(0).contents)
}

/// Generates the output in the requested layout.
///
/// The first file is always `mod.rs`; the rest are its parts, and the last is
/// `names.json` — an index of where every function ended up.
///
/// # Errors
///
/// As [`generate`].
pub fn generate_files(module: &Module, layout: Layout) -> Result<Vec<GeneratedFile>> {
    generate_options(
        module,
        &Options {
            layout,
            ..Options::default()
        },
    )
}

/// Everything a caller can ask the emitter for.
///
/// A struct rather than more parameters: there are already four ways to ask
/// for output and combining them pairwise is how an emitter ends up with eight
/// entry points that disagree.
#[derive(Debug, Clone, Default)]
pub struct Options {
    /// How the output is spread across files.
    pub layout: Layout,
    /// Decompile only these, stubbing the rest.
    pub only: Option<std::collections::BTreeSet<u32>>,
    /// Names for library code the module does not name.
    pub signatures: Signatures,
    /// Route every memory write through the watchpoint-aware runtime, so a
    /// host can ask which function wrote an address. Costs a comparison per
    /// write when nothing is watched, and nothing at all when it is not set.
    pub instrument_stores: bool,
    /// Write `offsets.json` beside the output: which bytes of the wasm file
    /// produced each generated line.
    pub map_offsets: bool,
}

/// Generates with [`Options`].
///
/// # Errors
///
/// As [`generate`].
pub fn generate_options(module: &Module, options: &Options) -> Result<Vec<GeneratedFile>> {
    let mut generator = Generator::new(module, options.layout);
    generator.only = options.only.clone();
    generator.signatures = options.signatures.clone();
    generator.instrument = options.instrument_stores;
    generator.map_offsets = options.map_offsets;
    generator.run()
}

/// Generates only the named functions, leaving the rest as stubs.
///
/// For reading rather than running: three functions out of thirteen thousand
/// is a different task from decompiling a module, and it should not cost 365
/// megabytes to do. The functions left out keep their signatures and their
/// names, so the result still compiles — it just cannot run past one of them.
///
/// # Errors
///
/// As [`generate`].
pub fn generate_only(
    module: &Module,
    layout: Layout,
    only: &std::collections::BTreeSet<u32>,
) -> Result<Vec<GeneratedFile>> {
    generate_options(
        module,
        &Options {
            layout,
            only: Some(only.clone()),
            ..Options::default()
        },
    )
}

/// A catalogue of fingerprints to names, for recognising library code.
///
/// Built from a module that kept its name section — usually one compiled on
/// purpose with the same toolchain as the target. What it buys is a real name
/// for a function that has none: `memcpy` rather than `f8421`.
pub type Signatures = std::collections::HashMap<u64, String>;

/// Extracts a signature catalogue from a module that has names.
///
/// Only functions long enough to be distinctive, and only ones the module
/// names — there is nothing to catalogue otherwise.
///
/// A fingerprint two differently-named functions share is dropped rather than
/// resolved: the constants are what told them apart, and they are exactly what
/// the fingerprint leaves out. Keeping either name would put a wrong one on
/// half the matches, and a wrong name is worse than `f8421`.
#[must_use]
pub fn extract_signatures(module: &Module) -> Signatures {
    let import_count = module.func_imports.len() as u32;
    let mut signatures = Signatures::new();
    let mut ambiguous = std::collections::HashSet::new();
    for (at, func) in module.funcs.iter().enumerate() {
        if func.body.len() < analysis::FINGERPRINT_FLOOR {
            continue;
        }
        let Some(name) = module.func_name(import_count + at as u32) else {
            continue;
        };
        let fingerprint = analysis::fingerprint(module, func);
        match signatures.get(&fingerprint) {
            Some(existing) if existing == name => {}
            Some(_) => {
                signatures.remove(&fingerprint);
                ambiguous.insert(fingerprint);
            }
            None if ambiguous.contains(&fingerprint) => {}
            None => {
                signatures.insert(fingerprint, name.to_string());
            }
        }
    }
    signatures
}

/// Generates with a signature catalogue, naming what it recognises.
///
/// # Errors
///
/// As [`generate`].
pub fn generate_with_signatures(
    module: &Module,
    layout: Layout,
    signatures: &Signatures,
) -> Result<Vec<GeneratedFile>> {
    generate_options(
        module,
        &Options {
            layout,
            signatures: signatures.clone(),
            ..Options::default()
        },
    )
}

struct Generator<'a> {
    module: &'a Module,
    layout: Layout,
    analysis: Analysis,
    out: String,
    parts: Vec<GeneratedFile>,
    /// Which functions to decompile, when only some were asked for.
    only: Option<std::collections::BTreeSet<u32>>,
    /// Fingerprints of known library code, to name what it recognises.
    signatures: Signatures,
    /// The names those fingerprints matched, by function index.
    recognised: std::collections::BTreeMap<u32, String>,
    /// Whether every memory write reports itself to a watchpoint.
    instrument: bool,
    /// Whether to build the line-to-bytes map.
    map_offsets: bool,
    /// Per function: its index, how many lines of its chunk come before its
    /// body, and the body's own line-to-bytes spans.
    spans: Vec<FunctionSpans>,
    /// Where each function ended up, for the index.
    located: Vec<(u32, String, String, usize)>,
}

impl<'a> Generator<'a> {
    fn new(module: &'a Module, layout: Layout) -> Self {
        Self {
            module,
            layout,
            analysis: analysis::analyse(module),
            out: String::new(),
            parts: Vec::new(),
            only: None,
            signatures: Signatures::new(),
            recognised: Default::default(),
            instrument: false,
            map_offsets: false,
            spans: Vec::new(),
            located: Vec::new(),
        }
    }

    /// Whether the module declared a shared memory, which is what a threaded
    /// build asks for and what decides the memory type in the output.
    fn is_threaded(&self) -> bool {
        self.module
            .memory
            .as_ref()
            .is_some_and(|memory| memory.shared)
    }

    /// The runtime memory type this module's instance holds.
    fn memory_type(&self) -> &'static str {
        if self.is_threaded() {
            "rt::SharedMemory"
        } else {
            "rt::Memory"
        }
    }

    /// How an import method spells its caller.
    fn caller_type(&self) -> &'static str {
        if self.is_threaded() {
            "rt::Caller<'_, rt::SharedMemory>"
        } else {
            "rt::Caller<'_>"
        }
    }

    /// Matches the module's functions against the signature catalogue.
    ///
    /// A fingerprint that occurs twice *in this module* names nothing, for the
    /// same reason one that occurs twice in the catalogue does: the fingerprint
    /// is a deliberately coarse equivalence class, and two functions in it are
    /// two functions. Deduplicating only the catalogue would put one library
    /// name on every member of the class.
    fn recognise(&mut self) {
        if self.signatures.is_empty() {
            return;
        }
        let import_count = self.module.func_imports.len() as u32;
        let mut seen: std::collections::HashMap<u64, usize> = std::collections::HashMap::new();
        for func in &self.module.funcs {
            if func.body.len() >= analysis::FINGERPRINT_FLOOR {
                *seen
                    .entry(analysis::fingerprint(self.module, func))
                    .or_default() += 1;
            }
        }
        for (at, func) in self.module.funcs.iter().enumerate() {
            if func.body.len() < analysis::FINGERPRINT_FLOOR {
                continue;
            }
            let index = import_count + at as u32;
            // What the module says about itself wins; this fills gaps.
            if self.module.func_name(index).is_some() {
                continue;
            }
            let fingerprint = analysis::fingerprint(self.module, func);
            if seen.get(&fingerprint).copied().unwrap_or_default() > 1 {
                continue;
            }
            if let Some(name) = self.signatures.get(&fingerprint) {
                self.recognised.insert(index, name.clone());
            }
        }
    }

    fn run(mut self) -> Result<Vec<GeneratedFile>> {
        self.recognise();
        self.header();
        self.registered_api();
        self.shared_state();
        self.embed_runtime();
        self.data_constants();
        self.table_types()?;
        self.imports_trait();
        self.instance_struct();
        self.instance_impl()?;
        let index = self.index_json();
        let offsets = self.map_offsets.then(|| self.offsets_json());
        let mut files = vec![GeneratedFile {
            name: "mod.rs".to_string(),
            contents: self.out,
        }];
        files.append(&mut self.parts);
        files.push(GeneratedFile {
            name: "names.json".to_string(),
            contents: index,
        });
        if let Some(offsets) = offsets {
            files.push(GeneratedFile {
                name: "offsets.json".to_string(),
                contents: offsets,
            });
        }
        Ok(files)
    }

    /// Which bytes of the wasm file produced each generated line.
    ///
    /// Patching a module by hand means computing an LEB encoding and counting
    /// bytes to find the pattern to replace, and an arithmetic slip there does
    /// not look like a slip — the pattern is simply not found, which reads as
    /// "the code changed". This is the map that removes the step: the line you
    /// are looking at, and the offset and length of the bytes behind it.
    ///
    /// A line covers every operator lowered since the previous one, so the
    /// operands folded into it are inside its span rather than missing from
    /// the map. Lines that are not lowered from an operator — a `let` for a
    /// local, a closing brace — are not in it.
    ///
    /// The bytes themselves are not here: they would be most of the module
    /// again, in hex. `unwasm bytes <module> <offset> <length>` prints them,
    /// and says whether the sequence is unique — which is the other half of
    /// the question a patch asks.
    fn offsets_json(&self) -> String {
        // Keyed by the located functions rather than by the spans, because a
        // function left out by `--only` is placed but has no body to map.
        let mapped: std::collections::BTreeMap<u32, (usize, &Vec<LineSpan>)> = self
            .spans
            .iter()
            .map(|(index, before, spans)| (*index, (*before, spans)))
            .collect();
        let mut out = String::from("{\n  \"functions\": [\n");
        let mut written = 0;
        for (index, _, file, start) in &self.located {
            let Some((before_body, spans)) = mapped.get(index) else {
                continue;
            };
            if written > 0 {
                out.push_str(",\n");
            }
            written += 1;
            let _ = write!(
                out,
                "    {{\"index\": {index}, \"file\": \"{file}\", \"lines\": [",
            );
            for (at, (line, offset, length)) in spans.iter().enumerate() {
                if at > 0 {
                    out.push_str(", ");
                }
                let _ = write!(out, "[{}, {offset}, {length}]", start + before_body + line);
            }
            out.push(']');
            out.push('}');
        }
        out.push_str("\n  ]\n}\n");
        out
    }

    /// An index of every function: what it is called, and where it is.
    ///
    /// Hand-written JSON rather than a dependency — it has four fields and no
    /// nesting. What it buys is not having to `grep -n` through two million
    /// lines to find the function you already know the number of.
    fn index_json(&self) -> String {
        let mut out = String::from("{\n  \"functions\": [\n");
        for (at, (index, name, file, line)) in self.located.iter().enumerate() {
            let slots: Vec<String> = self
                .analysis
                .table
                .iter()
                .filter(|(_, func)| *func == index)
                .map(|(slot, _)| slot.to_string())
                .collect();
            let source = if self.module.func_name(*index).is_some() {
                "name section"
            } else if self.recognised.contains_key(index) {
                "signature"
            } else {
                match self.analysis.derived_names.get(index).map(|d| d.source) {
                    Some(crate::analysis::NameSource::Assert) => "assert",
                    Some(crate::analysis::NameSource::Message { .. }) => "message",
                    None => "none",
                }
            };
            let numbers = |set: &std::collections::BTreeSet<u32>| {
                set.iter()
                    .map(u32::to_string)
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let calls = numbers(self.analysis.call_graph.calls_from(*index));
            let called_by = numbers(self.analysis.call_graph.callers_of(*index));
            let sites = self.analysis.call_graph.sites_reaching(*index);
            let _ = writeln!(
                out,
                "    {{\"index\": {index}, \"name\": \"{name}\", \"file\": \"{file}\", \"line\": {line}, \"named_by\": \"{source}\", \"table_slots\": [{}], \"calls\": [{calls}], \"called_by\": [{called_by}], \"call_sites\": {sites}}}{}",
                slots.join(", "),
                if at + 1 == self.located.len() {
                    ""
                } else {
                    ","
                }
            );
        }
        out.push_str("  ]\n}\n");
        out
    }

    fn header(&mut self) {
        self.out.push_str(concat!(
            "// Generated by unwasm. Do not edit: regenerate from the module.\n",
            "//\n",
            "// This is level 0 — a faithful translation. Linear memory is a byte\n",
            "// vector and every wasm value type is its Rust counterpart, so the\n",
            "// arithmetic, the traps and the memory layout are the module's own.\n",
            "// Names come from the module where it kept them and from indices\n",
            "// where it did not.\n",
            "\n",
            "#![allow(\n",
            "    dead_code,\n",
            "    unused_mut,\n",
            "    unused_variables,\n",
            "    unused_assignments,\n",
            "    unused_labels,\n",
            "    unused_parens,\n",
            "    unreachable_code,\n",
            "    non_snake_case,\n",
            "    clippy::all,\n",
            "    clippy::pedantic\n",
            ")]\n\n",
        ));
    }

    /// The API the module registers with embind, as a comment at the top.
    ///
    /// This is what the module says it is for. Everything else in the output is
    /// what the compiler left behind; this is what the author published, and on
    /// a stripped module it is the only such thing there is.
    fn registered_api(&mut self) {
        // A constructor has no name argument — it has a signature, and its
        // class. Filtering on the name alone drops exactly those.
        let named: Vec<&crate::analysis::Registration> = self
            .analysis
            .registrations
            .iter()
            .filter(|registration| registration.name.is_some() || registration.signature.is_some())
            .collect();
        if named.is_empty() {
            return;
        }
        let _ = writeln!(
            self.out,
            "// The API this module registers with embind at startup — {} of {}\n// registrations name themselves:\n//",
            named.len(),
            self.analysis.registrations.len()
        );
        for registration in named {
            let kind = registration
                .kind
                .trim_start_matches("_embind_register_")
                .replace('_', " ");
            // The signature where there is one: embind records the argument
            // types as well as the name, and they are the only types in a
            // stripped module that have names.
            match (&registration.signature, &registration.class) {
                (Some(signature), Some(class)) => {
                    let _ = writeln!(
                        self.out,
                        "//   {kind}: {}::{}",
                        escape_doc(class),
                        escape_doc(signature)
                    );
                }
                (Some(signature), None) => {
                    let _ = writeln!(self.out, "//   {kind}: {}", escape_doc(signature));
                }
                (None, _) => {
                    let _ = writeln!(
                        self.out,
                        "//   {kind}: {}",
                        escape_doc(registration.name.as_deref().unwrap_or_default())
                    );
                }
            }
        }
        self.out.push('\n');
    }

    /// The addresses the module shares most widely, at the top.
    ///
    /// Individually each one is annotated where it is used; together they are
    /// a map of the module's shared state, which is worth having in one place.
    fn shared_state(&mut self) {
        if self.analysis.hot_addresses.is_empty() {
            return;
        }
        let mut by_use: Vec<(&i32, &usize)> = self.analysis.hot_addresses.iter().collect();
        by_use.sort_by_key(|(address, functions)| (std::cmp::Reverse(**functions), **address));
        let _ = writeln!(
            self.out,
            "// Addresses shared across the module — {} of them, each referenced by at\n// least {HOT_ADDRESS_FUNCTIONS} functions and holding no text. The widest twenty:\n//",
            by_use.len()
        );
        for (address, functions) in by_use.iter().take(20) {
            let _ = writeln!(self.out, "//   {address:<10} {functions} functions");
        }
        self.out.push('\n');
    }

    fn embed_runtime(&mut self) {
        self.out.push_str("pub mod rt {\n");
        for line in runtime_source().lines() {
            if line.is_empty() {
                self.out.push('\n');
            } else {
                let _ = writeln!(self.out, "    {line}");
            }
        }
        self.out.push_str("}\n\n");
    }

    /// The data segments, as byte-string literals.
    ///
    /// `b"..."` rather than `&[0x41, 0x42, …]`, and the difference is not
    /// cosmetic: an array literal is one expression node per byte, so the VoIP
    /// module's 1.25 MB of data became 1.25 million nodes and 7.9 MB of source
    /// for rustc to parse, name-resolve and const-evaluate. A literal is one
    /// token. Most of these bytes are text, which costs one character each.
    fn data_constants(&mut self) {
        for (index, segment) in self.module.datas.iter().enumerate() {
            let _ = writeln!(
                self.out,
                "const DATA_{index}: &[u8] = {};\n",
                byte_string(segment.bytes.iter().copied())
            );
        }
    }

    /// The host side of the module, as a trait.
    ///
    /// Imports are the one thing a module cannot answer for itself, so they
    /// become required methods rather than stubs returning zero. [`NoImports`]
    /// traps, which keeps "nobody supplied a host" distinguishable from "the
    /// host returned 0" — the distinction the oracle work in wa-wasm-oracle
    /// found the hard way.
    /// Whether an import is one this backend generates rather than asks for.
    fn is_generated(&self, index: usize) -> bool {
        self.analysis
            .invokes
            .iter()
            .any(|invoke| invoke.import == index as u32)
            || self
                .analysis
                .spawn
                .is_some_and(|spawn| spawn.import == index as u32)
            || self
                .analysis
                .init_main_thread
                .is_some_and(|init| init.import == index as u32)
    }

    fn imports_trait(&mut self) {
        if self.analysis.spawn.is_some() {
            self.out.push_str(concat!(
                "/// What the module needs from its host.\n",
                "///\n",
                "/// `Clone + Send + 'static` because this module creates threads: a new\n",
                "/// thread is another instance over the same memory, and it needs a host\n",
                "/// of its own. What `clone` gives it is your decision — a copy, or a\n",
                "/// handle to one shared host. A copy means a file the thread writes is\n",
                "/// invisible to the others, which for a filesystem is usually wrong; put\n",
                "/// the state behind an `Arc<Mutex<_>>` and clone that.\n",
                "pub trait Imports: Clone + Send + 'static {\n",
            ));
        } else {
            self.out
                .push_str("/// What the module needs from its host.\npub trait Imports {\n");
        }
        if !self.analysis.invokes.is_empty() {
            let _ = writeln!(
                self.out,
                "    // {} `invoke_*` imports are not here: they are Emscripten's\n    // exception trampolines, and every part of one is already in this\n    // module — the table, the stack pointer, and its own `setThrew`. They\n    // are generated below rather than asked of you.",
                self.analysis.invokes.len()
            );
        }
        for (index, import) in self.module.func_imports.iter().enumerate() {
            if self.is_generated(index) {
                continue;
            }
            let ty = self.module.types.get(import.type_index as usize);
            let signature = ty.map_or_else(String::new, signature_of);
            let result = ty.map_or_else(String::new, return_type);
            let caller = self.caller_type();
            let _ = writeln!(
                self.out,
                "    /// `{}::{}`\n    fn {}(&mut self, caller: &mut {caller}{signature}) {result};",
                import.module,
                import.field,
                import_ident(import.module.as_str(), import.field.as_str())
            );
        }
        self.out.push_str("}\n\n");

        self.out.push_str(concat!(
            "/// A host that supplies nothing.\n",
            "///\n",
            "/// Every import traps rather than returning a plausible zero: a stub\n",
            "/// that returns zero is a hypothesis, and the module cannot tell it\n",
            "/// apart from an answer.\n",
            "#[derive(Debug, Default, Clone, Copy)]\n",
            "pub struct NoImports;\n\n",
            "impl Imports for NoImports {\n",
        ));
        for (index, import) in self.module.func_imports.iter().enumerate() {
            if self.is_generated(index) {
                continue;
            }
            let ty = self.module.types.get(import.type_index as usize);
            let signature = ty.map_or_else(String::new, signature_of);
            let result = ty.map_or_else(String::new, return_type);
            let caller = self.caller_type();
            let _ = writeln!(
                self.out,
                "    fn {}(&mut self, _caller: &mut {caller}{signature}) {result} {{\n        rt::trap(\"unimplemented import: {}::{}\");\n    }}",
                import_ident(import.module.as_str(), import.field.as_str()),
                import.module,
                import.field
            );
        }
        self.out.push_str("}\n\n");
    }

    fn instance_struct(&mut self) {
        let memory_note = if self.is_threaded() {
            "    /// Linear memory, shared with every other instance over it —\n    /// which is what a thread of this module is.\n"
        } else {
            "    /// Linear memory.\n"
        };
        self.out.push_str(concat!(
            "/// An instantiated module: its memory, its table and its globals.\n",
            "pub struct Instance<H: Imports = NoImports> {\n",
            "    /// The host.\n    pub host: H,\n",
        ));
        self.out.push_str(memory_note);
        let _ = writeln!(self.out, "    pub memory: {},", self.memory_type());
        self.out.push_str(concat!(
            "    /// The function table `call_indirect` dispatches through.\n",
            "    /// `u32::MAX` marks an empty slot.\n    pub table: Vec<u32>,\n",
            "    /// Which data segments have been dropped. An active segment is\n",
            "    /// dropped by instantiation itself, as the spec requires.\n",
            "    pub data_dropped: Vec<bool>,\n",
        ));
        for (index, global) in self.module.globals.iter().enumerate() {
            let mutability = if global.mutable {
                "mutable"
            } else {
                "immutable"
            };
            let _ = writeln!(
                self.out,
                "    /// Global #{index} ({mutability}).{}\n    pub {}: {},",
                self.global_note(index as u32),
                global_ident(index as u32, &self.analysis),
                global.ty.rust_name()
            );
        }
        self.out.push_str("}\n\n");
    }

    /// Pages a threaded module's memory is given room to grow into.
    ///
    /// 1024 pages is 64 MiB — enough for a real program's heap during startup
    /// and small enough to allocate without thinking about it. The VoIP module
    /// declares a 2 GiB maximum, which nobody wants allocated up front.
    const DEFAULT_RESERVATION: u32 = 1024;

    fn instance_impl(&mut self) -> Result<()> {
        self.out.push_str("impl<H: Imports> Instance<H> {\n");
        if !self.is_threaded() {
            self.out.push_str("    /// Instantiates the module: memory, data segments, table, then `start`.\n    pub fn with_host(host: H) -> Self {\n");
        }
        let memory = self
            .module
            .memory
            .clone()
            .unwrap_or(crate::module::MemoryDef {
                min_pages: 0,
                max_pages: None,
                shared: false,
                imported: None,
            });
        let max = match memory.max_pages {
            Some(pages) => format!("Some({pages})"),
            None => "None".to_string(),
        };
        if self.is_threaded() {
            // A shared memory cannot be reallocated while another thread holds
            // it, so its size is reserved up front. The default covers the
            // module's own declaration and leaves room to grow; a host that
            // needs more says so, and one that grows past it gets -1 rather
            // than a memory that moved under another thread's feet.
            let _ = writeln!(
                self.out,
                "    /// Instantiates with the default reservation of {} pages.\n    ///\n    /// A shared memory is allocated once and never moves, so how far it\n    /// can grow is decided here rather than by the first `memory.grow`.\n    pub fn with_host(host: H) -> Self {{\n        Self::with_host_and_reservation(host, {})\n    }}\n",
                Self::DEFAULT_RESERVATION.max(memory.min_pages),
                Self::DEFAULT_RESERVATION.max(memory.min_pages)
            );
            let _ = writeln!(
                self.out,
                "    /// Instantiates with room to grow to `reserved_pages`.\n    pub fn with_host_and_reservation(host: H, reserved_pages: u32) -> Self {{"
            );
        }
        let allocate = if self.is_threaded() {
            format!(
                "rt::SharedMemory::new({}, {max}, reserved_pages)",
                memory.min_pages
            )
        } else {
            format!("rt::Memory::new({}, {max})", memory.min_pages)
        };
        let _ = writeln!(
            self.out,
            "        let mut instance = Self {{\n            host,\n            memory: {allocate},\n            table: Vec::new(),\n            data_dropped: vec![false; {}],",
            self.module.datas.len()
        );
        for (index, global) in self.module.globals.iter().enumerate() {
            let _ = writeln!(
                self.out,
                "            {}: {},",
                global_ident(index as u32, &self.analysis),
                const_expr_literal(global.init)
            );
        }
        self.out.push_str("        };\n");

        for (index, segment) in self.module.datas.iter().enumerate() {
            if let Some(offset) = segment.offset {
                let _ = writeln!(
                    self.out,
                    "        instance.memory.init({}, DATA_{index}, 0, DATA_{index}.len() as i32);\n        instance.data_dropped[{index}] = true;",
                    const_expr_literal(offset)
                );
            }
        }

        let table_size = self.table_size();
        if table_size > 0 {
            let _ = writeln!(
                self.out,
                "        instance.table = vec![u32::MAX; {table_size}];"
            );
            for segment in &self.module.elems {
                let Some(ConstExpr::I32(base)) = segment.offset else {
                    continue;
                };
                for (slot, func) in segment.funcs.iter().enumerate() {
                    let _ = writeln!(
                        self.out,
                        "        instance.table[{}] = {func};",
                        base as usize + slot
                    );
                }
            }
        }

        if let Some(start) = self.module.start {
            let _ = writeln!(
                self.out,
                "        instance.{}();",
                function_ident_with(start, &self.analysis, &self.recognised)
            );
        }
        self.out.push_str("        instance\n    }\n\n");

        if self.is_threaded() {
            self.out.push_str(concat!(
                "    /// Another instance of this module over the same memory: a thread.\n",
                "    ///\n",
                "    /// This is what Emscripten's pthreads are. The memory and the table\n",
                "    /// are shared; the globals are not, which is the point — each thread\n",
                "    /// has its own `__stack_pointer`, and the host is expected to give it\n",
                "    /// a stack of its own before it runs anything.\n",
                "    ///\n",
                "    /// The data segments are *not* placed again. An engine does not\n",
                "    /// re-run them for a new thread either: the bytes are already in the\n",
                "    /// memory this instance is joining, and placing them a second time\n",
                "    /// would overwrite whatever the running program has done to them.\n",
                "    ///\n",
                "    /// The table is copied rather than shared, and that is not the\n",
                "    /// divergence it looks like: nothing can change a table here. This\n",
                "    /// decompiler has no `table.set`, `table.grow`, `table.fill` or\n",
                "    /// `table.copy` — an opcode it does not model is refused by name, not\n",
                "    /// dropped — so a module that mutated its table would not have\n",
                "    /// decompiled at all. A copy of something immutable is the original.\n",
                "    pub fn spawn<G: Imports>(&self, host: G) -> Instance<G> {\n",
                "        Instance {\n",
                "            host,\n",
                "            memory: self.memory.clone(),\n",
                "            table: self.table.clone(),\n",
                "            data_dropped: self.data_dropped.clone(),\n",
            ));
            for (index, global) in self.module.globals.iter().enumerate() {
                let _ = writeln!(
                    self.out,
                    "            {}: {},",
                    global_ident(index as u32, &self.analysis),
                    const_expr_literal(global.init)
                );
            }
            self.out.push_str("        }\n    }\n\n");
        }

        self.export_wrappers();
        self.import_thunks();
        self.indirect_dispatchers()?;
        // Closes the `impl` block, and emits the functions either inside it or
        // into part files beside it.
        self.functions()?;
        // `new` lives on the concrete instantiation rather than on the generic
        // impl: `Instance::new()` inside `impl<H> Instance<H>` cannot infer `H`
        // at the call site, and every caller would have to spell it out.
        self.out.push_str(concat!(
            "impl Instance<NoImports> {\n",
            "    /// Instantiates with a host that traps on every import.\n",
            "    #[must_use]\n",
            "    pub fn new() -> Self {\n        Self::with_host(NoImports)\n    }\n}\n\n",
            "impl Default for Instance<NoImports> {\n",
            "    fn default() -> Self {\n        Self::new()\n    }\n}\n",
        ));
        Ok(())
    }

    /// Emits the module's functions and closes the `impl` block they live in.
    ///
    /// Under [`Layout::Split`] they go into sibling modules instead, each with
    /// its own `impl` block on the same type — which is legal Rust, and is what
    /// gives rustc the module boundaries it partitions codegen units along.
    fn functions(&mut self) -> Result<()> {
        let import_count = self.module.func_imports.len() as u32;
        let budget = match self.layout {
            Layout::Single => {
                // Counted forward rather than recounted. `self.out.lines()`
                // walks everything written so far, and doing that once per
                // function is quadratic in the size of the output: on a 3.3 MiB
                // capture it was 152 of the 154 seconds a decompilation took,
                // and on the 10.2 MiB one it was twenty-five minutes. Each body
                // ends in a newline, so the count of what is already there plus
                // the count of what is being added is the count of the whole.
                let mut lines = self.out.lines().count();
                for (at, func) in self.module.funcs.iter().enumerate() {
                    let index = import_count + at as u32;
                    let body = self.function(index, func)?;
                    self.located.push((
                        index,
                        function_ident_with(index, &self.analysis, &self.recognised),
                        "mod.rs".to_string(),
                        lines + 1,
                    ));
                    lines += body.lines().count();
                    self.out.push_str(&body);
                }
                self.out.push_str("}\n\n");
                return Ok(());
            }
            // A zero budget would put every function in a file of its own, and
            // that is the most it can mean.
            Layout::Split { lines_per_file } => lines_per_file.max(1),
        };

        self.out.push_str("}\n\n");

        // Fill each part up to the budget. A function larger than the whole
        // budget still goes in one piece — a function cannot span modules — so
        // it lands in a file of its own rather than dragging fifteen others
        // into a million-line compilation unit with it.
        let mut current = String::new();
        let mut lines = 0usize;
        for (at, func) in self.module.funcs.iter().enumerate() {
            let index = import_count + at as u32;
            let body = self.function(index, func)?;
            let body_lines = body.lines().count();
            if lines > 0 && lines + body_lines > budget {
                self.push_part(std::mem::take(&mut current));
                lines = 0;
            }
            let file = format!("part{}.rs", self.parts.len());
            self.located.push((
                index,
                function_ident_with(index, &self.analysis, &self.recognised),
                file,
                part_prelude_lines() + lines + 1,
            ));
            current.push_str(&body);
            lines += body_lines;
        }
        if !current.is_empty() {
            self.push_part(current);
        }

        for part in 0..self.parts.len() {
            let _ = writeln!(self.out, "mod part{part};");
        }
        self.out.push('\n');
        Ok(())
    }

    fn push_part(&mut self, functions: String) {
        let mut contents = String::new();
        contents.push_str(PART_HEADER);
        contents.push_str(PART_OPENING);
        contents.push_str(&functions);
        contents.push_str("}\n");
        let name = format!("part{}.rs", self.parts.len());
        self.parts.push(GeneratedFile { name, contents });
    }

    /// The doc comment a global carries when the analysis recognised it.
    ///
    /// The evidence goes in the comment rather than only in the name: "this is
    /// the stack pointer" is a claim, and the reader deserves to see what it
    /// rests on.
    fn global_note(&self, index: u32) -> String {
        match self.analysis.stack_pointer {
            Some(found) if found.global == index => match found.evidence {
                Evidence::Exported => {
                    "\n    ///\n    /// The C stack pointer: the module exports it under that name."
                        .to_string()
                }
                Evidence::Named => {
                    "\n    ///\n    /// The C stack pointer: the module's name section calls it that."
                        .to_string()
                }
                Evidence::Prologue { functions } => format!(
                    "\n    ///\n    /// The C stack pointer, by its use: {functions} functions open by\n    /// subtracting a frame from it and storing it back. The module keeps\n    /// no names, so this is evidence rather than a declaration."
                ),
            },
            _ => String::new(),
        }
    }

    fn table_size(&self) -> usize {
        self.module
            .elems
            .iter()
            .filter_map(|segment| match segment.offset {
                Some(ConstExpr::I32(base)) => Some(base as usize + segment.funcs.len()),
                _ => None,
            })
            .max()
            .unwrap_or(0)
    }

    /// Exports become public methods, so a caller reaches the module by the
    /// name the module publishes rather than by an index.
    fn export_wrappers(&mut self) {
        for (export, name) in exported_functions(self.module) {
            let Some(ty) = self.module.func_type(export.index) else {
                continue;
            };
            let args: Vec<String> = (0..ty.params.len()).map(|at| format!("p{at}")).collect();
            let _ = writeln!(
                self.out,
                "    /// Exported as `{}`.\n    pub fn {name}(&mut self{}) {} {{\n        self.{}({})\n    }}\n",
                escape_doc(&export.name),
                signature_of(ty),
                return_type(ty),
                function_ident_with(export.index, &self.analysis, &self.recognised),
                args.join(", ")
            );
        }
        // A memory or global export tells a reader where the module's own
        // metadata lives, and costs one line to record.
        for export in &self.module.exports {
            match export.kind {
                ExportKind::Global => {
                    let _ = writeln!(
                        self.out,
                        "    /// The module exports global #{} as `{}`.\n    pub fn exported_global_{}(&self) -> {} {{\n        self.{}\n    }}\n",
                        export.index,
                        escape_doc(&export.name),
                        sanitize(&export.name),
                        self.module
                            .globals
                            .get(export.index as usize)
                            .map_or("i32", |global| global.ty.rust_name()),
                        global_ident(export.index, &self.analysis)
                    );
                }
                ExportKind::Memory | ExportKind::Table | ExportKind::Func => {}
            }
        }
    }

    /// Calls to imported functions go through a thunk, so a call site reads the
    /// same whether the callee is defined here or supplied by the host.
    ///
    /// An `invoke_*` import gets a generated trampoline instead — see
    /// [`Self::invoke_trampoline`].
    fn import_thunks(&mut self) {
        for (index, import) in self.module.func_imports.iter().enumerate() {
            let Some(ty) = self.module.types.get(import.type_index as usize) else {
                continue;
            };
            if let Some(invoke) = self
                .analysis
                .invokes
                .iter()
                .find(|invoke| invoke.import == index as u32)
                .copied()
            {
                let ty = ty.clone();
                self.invoke_trampoline(invoke, &ty, import.field.clone());
                continue;
            }
            if let Some(spawn) = self
                .analysis
                .spawn
                .filter(|spawn| spawn.import == index as u32)
            {
                self.spawn_trampoline(spawn);
                continue;
            }
            if let Some(init) = self
                .analysis
                .init_main_thread
                .filter(|init| init.import == index as u32)
            {
                self.init_main_thread_trampoline(init);
                continue;
            }
            let args: Vec<String> = (0..ty.params.len()).map(|at| format!("p{at}")).collect();
            // The caller is the first argument, so the rest need the comma the
            // trait signature already carries.
            let rest = if args.is_empty() {
                String::new()
            } else {
                format!(", {}", args.join(", "))
            };
            let _ = writeln!(
                self.out,
                "    /// Imported from `{}::{}`.\n    pub(crate) fn f{index}(&mut self{}) {} {{\n        let mut caller = rt::Caller {{\n            memory: &mut self.memory,\n        }};\n        self.host.{}(&mut caller{})\n    }}\n",
                import.module,
                import.field,
                signature_of(ty),
                return_type(ty),
                import_ident(import.module.as_str(), import.field.as_str()),
                rest
            );
        }
    }

    /// Emits `__pthread_create_js`, which the host cannot answer.
    ///
    /// It has to reach back into the instance — spawn a thread, join it to
    /// this memory, and call the start routine through the table — and the
    /// `Imports` trait has no way to do that. So it is generated, like the
    /// `invoke_*` trampolines and for the same reason: every part of it is
    /// already here.
    ///
    /// What the new thread does, in order, is what Emscripten's worker does:
    ///
    /// 1. **its stack**, read out of the pthread struct the guest filled in
    ///    inside `pthread_create`. The glue's `establishStackSpace` does this
    ///    first and it is not optional: four threads on one stack left a frame
    ///    with 0 of its 64 fields intact, measured.
    /// 2. `_emscripten_stack_set_limits(high, low)`, so the module's own
    ///    overflow checks know where this thread's stack is.
    /// 3. `_emscripten_thread_init(thread, 0, 0, 1, 0, 0)` — the arguments the
    ///    glue passes, `can_block` included.
    /// 4. the start routine, through the table, with its argument.
    /// 5. `_emscripten_thread_exit(result)`, which is what a `pthread_join`
    ///    is waiting for.
    ///
    /// It returns 0 — the thread was created — and a host that wants to refuse
    /// a thread has no say, which is the one place this differs from the glue.
    fn spawn_trampoline(&mut self, spawn: crate::analysis::Spawn) {
        let index = spawn.import;
        let init = function_ident_with(spawn.thread_init, &self.analysis, &self.recognised);
        // `(pthread_ptr, is_main, is_runtime, can_block, default_stacksize,
        // start_profiling)` in the version that takes six. A version that takes
        // fewer gets the prefix it takes.
        let init_arguments = ["p0", "0", "0", "1", "0", "0"]
            .iter()
            .take(spawn.thread_init_arity.max(1))
            .copied()
            .collect::<Vec<_>>()
            .join(", ");
        let (stack, size) = crate::analysis::Analysis::PTHREAD_STACK_OFFSETS;

        let mut lines = vec![
            "    /// `env::__pthread_create_js`, generated rather than asked of the host:"
                .to_string(),
            "    /// a thread is another instance over this memory, and only this side can"
                .to_string(),
            "    /// make one. The order is the glue's own — the stack out of the pthread"
                .to_string(),
            "    /// struct first, then its limits, then `_emscripten_thread_init`, then the"
                .to_string(),
            "    /// start routine through the table.".to_string(),
            format!(
                "    pub(crate) fn f{index}(&mut self, p0: i32, p1: i32, p2: i32, p3: i32) -> i32 {{"
            ),
            "        let _ = p1;".to_string(),
            "        let mut worker = self.spawn(self.host.clone());".to_string(),
        ];
        // The stack the guest allocated for this thread, where the guest wrote
        // it. Without a stack pointer there is nowhere to put it, and a thread
        // on another thread's stack destroys its frames.
        let has_stack = self.analysis.stack_pointer.is_some();
        if let Some(found) = self.analysis.stack_pointer {
            let name = global_ident(found.global, &self.analysis);
            lines.push(format!(
                "        let high = worker.memory.load32(p0, {stack});"
            ));
            lines.push(format!(
                "        let low = high - worker.memory.load32(p0, {size});"
            ));
            lines.push(format!("        worker.{name} = high;"));
        }
        lines.push("        std::thread::spawn(move || {".to_string());
        if has_stack {
            match spawn.stack_set_limits {
                Some(func) => lines.push(format!(
                    "            worker.{}(high, low);",
                    function_ident_with(func, &self.analysis, &self.recognised)
                )),
                None => lines.push("            let _ = low;".to_string()),
            }
        }
        lines.push(format!("            worker.{init}({init_arguments});"));
        match spawn.thread_exit {
            // What the glue's `finish` does: the joining thread is waiting for
            // exactly this, and without it `pthread_join` never returns.
            Some(func) => {
                lines.push(format!(
                    "            let result = worker.call_indirect_{}(p2, p3);",
                    spawn.entry_type
                ));
                lines.push(format!(
                    "            worker.{}(result);",
                    function_ident_with(func, &self.analysis, &self.recognised)
                ));
            }
            None => lines.push(format!(
                "            worker.call_indirect_{}(p2, p3);",
                spawn.entry_type
            )),
        }
        lines.push("        });".to_string());
        lines.push("        0".to_string());
        lines.push("    }".to_string());
        lines.push(String::new());
        let _ = writeln!(self.out, "{}", lines.join("\n"));
    }

    /// Emits `__emscripten_init_main_thread_js`, the main thread's own setup.
    ///
    /// The glue answers it by calling the module's `_emscripten_thread_init`
    /// with `is_main` and `is_runtime` set, which reaches back into the
    /// instance — so it is generated for the same reason `__pthread_create_js`
    /// is. The stack size argument is 0 because that is what the glue passes
    /// unless a build overrode `DEFAULT_PTHREAD_STACK_SIZE`, and 0 there means
    /// "use the module's own".
    fn init_main_thread_trampoline(&mut self, init: crate::analysis::InitMainThread) {
        let index = init.import;
        let name = function_ident_with(init.thread_init, &self.analysis, &self.recognised);
        let arguments = ["p0", "1", "1", "1", "0", "0"]
            .iter()
            .take(init.thread_init_arity.max(1))
            .copied()
            .collect::<Vec<_>>()
            .join(", ");
        let lines = [
            "    /// `env::__emscripten_init_main_thread_js`, generated: the glue answers"
                .to_string(),
            "    /// it with the module's own `_emscripten_thread_init`, and only this side"
                .to_string(),
            "    /// can call that.".to_string(),
            format!("    pub(crate) fn f{index}(&mut self, p0: i32) {{"),
            format!("        self.{name}({arguments});"),
            "    }".to_string(),
            String::new(),
        ];
        let _ = writeln!(self.out, "{}", lines.join("\n"));
    }

    /// Emits one `invoke_*` trampoline.
    ///
    /// This is Emscripten's glue, in Rust:
    ///
    /// ```js
    /// var sp = stackSave();
    /// try { getWasmTableEntry(index)(a, b); }
    /// catch (e) { stackRestore(sp); if (e !== e+0) throw e; _setThrew(1, 0); }
    /// ```
    ///
    /// The `if (e !== e+0) throw e` is the part worth copying carefully: the
    /// glue re-throws anything that is not one of its own exceptions, so a trap
    /// stays a trap. Catching everything would turn a crash into a quietly
    /// handled error, which is the failure mode a decompiler must not have.
    fn invoke_trampoline(
        &mut self,
        invoke: crate::analysis::Invoke,
        ty: &crate::module::FuncType,
        field: String,
    ) {
        let index = invoke.import;
        let args: Vec<String> = (1..ty.params.len()).map(|at| format!("p{at}")).collect();
        let stack_pointer = global_ident(
            self.analysis
                .stack_pointer
                .expect("a trampoline is only generated with one")
                .global,
            &self.analysis,
        );
        let set_threw_ident = function_ident_with(
            self.analysis
                .set_threw
                .expect("a trampoline is only generated with one"),
            &self.analysis,
            &self.recognised,
        );
        let zero = ty.results.first().map_or("", |result| result.zero());

        let _ = writeln!(
            self.out,
            "    /// `env::{field}` — generated, not delegated.\n    ///\n    /// Emscripten's exception trampoline: call through the table, and if the\n    /// callee throws, restore the stack pointer and tell the module through\n    /// its own `setThrew`. A trap is not an exception and is re-raised.\n    fn f{index}(&mut self{}) {} {{\n        let saved = self.{stack_pointer};\n        let outcome = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {{\n            self.call_indirect_{}(p0{}{})\n        }}));\n        match outcome {{\n            Ok(value) => value,\n            Err(payload) => {{\n                if payload.is::<rt::GuestException>() {{\n                    self.{stack_pointer} = saved;\n                    self.{set_threw_ident}(1, 0);\n                    {zero}\n                }} else {{\n                    std::panic::resume_unwind(payload)\n                }}\n            }}\n        }}\n    }}\n",
            signature_of(ty),
            return_type(ty),
            invoke.callee_type,
            if args.is_empty() { "" } else { ", " },
            args.join(", ")
        );
    }

    /// `call_indirect` becomes a match over the table, one dispatcher per
    /// signature. The type check wasm does at run time is the match arm's
    /// guard: a slot holding a function of another signature falls through to
    /// the trap, exactly as the engine would.
    /// What the table holds, by type, and a way to call it from outside.
    ///
    /// An embind registration is a table index and nothing else: the module
    /// tells its host "call slot 4173 to reach `startVoipCall`", and a host
    /// with only `call_indirect_7` has to know that 4173 is of type 7. This
    /// emits the map and the call that uses it, so a driver can invoke
    /// anything the module registered without knowing its shape in advance.
    ///
    /// The map is a byte string of two bytes per slot, because 9290 numbers
    /// written out are 9290 expressions for the compiler to fold.
    fn table_types(&mut self) -> Result<()> {
        let size = self.table_size();
        if size == 0 {
            return Ok(());
        }
        let mut types = vec![u16::MAX; size];
        for (slot, func) in &self.analysis.table {
            let Some(index) = crate::analysis::type_index_of(self.module, *func) else {
                continue;
            };
            let Ok(index) = u16::try_from(index) else {
                // More than 65535 types is not a module anybody has; saying so
                // is better than truncating an index into a wrong signature.
                return Ok(());
            };
            if let Some(slot) = types.get_mut(*slot as usize) {
                *slot = index;
            }
        }
        let _ = writeln!(
            self.out,
            "/// The type of what each table slot holds, two bytes a slot, big-endian.\n\
             /// `u16::MAX` marks a slot the module left empty.\n\
             const TABLE_TYPE: &[u8] = {};\n",
            byte_string(types.iter().flat_map(|value| value.to_be_bytes()))
        );
        Ok(())
    }

    /// Emits the call that turns a table slot into an invocation.
    ///
    /// Arguments and results travel as `i64` because that is the only shape
    /// that holds every wasm value: an f64 goes as its bits rather than as a
    /// cast, which would round it. The same convention the default-answer
    /// record uses.
    fn invoke_by_slot(&mut self, signatures: &BTreeSet<u32>) {
        if self.table_size() == 0 {
            return;
        }
        self.out.push_str(concat!(
            "    /// The type of what a table slot holds, or `None` if it is empty.\n",
            "    #[must_use]\n",
            "    pub fn slot_type(&self, slot: i32) -> Option<u32> {\n",
            "        let at = slot as u32 as usize * 2;\n",
            "        let bytes = TABLE_TYPE.get(at..at + 2)?;\n",
            "        let ty = u32::from(u16::from_be_bytes([bytes[0], bytes[1]]));\n",
            "        (ty != u32::from(u16::MAX)).then_some(ty)\n",
            "    }\n\n",
            "    /// Calls whatever the table holds at `slot`.\n",
            "    ///\n",
            "    /// This is how a host reaches something the module only ever named by\n",
            "    /// index — an embind registration is a table slot and nothing else.\n",
            "    /// Values travel as `i64`, floats as their bits; `Err` says the slot is\n",
            "    /// empty, its type is one nothing dispatches, or the arguments do not\n",
            "    /// match the signature, rather than guessing at any of the three.\n",
            "    ///\n",
            "    /// # Errors\n",
            "    ///\n",
            "    /// As above.\n",
            "    pub fn invoke_slot(&mut self, slot: i32, args: &[i64]) -> Result<Option<i64>, String> {\n",
            "        let ty = self\n",
            "            .slot_type(slot)\n",
            "            .ok_or_else(|| format!(\"table slot {slot} is empty\"))?;\n",
            "        match ty {\n",
        ));
        for type_index in signatures {
            let Some(ty) = self.module.types.get(*type_index as usize) else {
                continue;
            };
            let arity = ty.params.len();
            let arguments: Vec<String> = ty
                .params
                .iter()
                .enumerate()
                .map(|(at, param)| match param {
                    ValType::I32 => format!("args[{at}] as i32"),
                    ValType::I64 => format!("args[{at}]"),
                    ValType::F32 => format!("f32::from_bits(args[{at}] as u32)"),
                    ValType::F64 => format!("f64::from_bits(args[{at}] as u64)"),
                })
                .collect();
            let call = format!(
                "self.call_indirect_{type_index}(slot{}{})",
                if arguments.is_empty() { "" } else { ", " },
                arguments.join(", ")
            );
            let result = match ty.results.first() {
                None => format!("{{ {call}; Ok(None) }}"),
                Some(ValType::I32 | ValType::I64) => format!("Ok(Some(i64::from({call})))"),
                Some(ValType::F32) => format!("Ok(Some(i64::from({call}.to_bits())))"),
                Some(ValType::F64) => format!("Ok(Some({call}.to_bits() as i64))"),
            };
            let _ = writeln!(
                self.out,
                "            {type_index} if args.len() == {arity} => {result},"
            );
        }
        self.out.push_str(concat!(
            "            other => Err(format!(\n",
            "                \"table slot {slot} holds type {other}, and {} arguments is not \\\n",
            "                 its arity\",\n",
            "                args.len()\n",
            "            )),\n",
            "        }\n",
            "    }\n\n",
        ));
    }

    fn indirect_dispatchers(&mut self) -> Result<()> {
        let mut signatures: BTreeSet<u32> = BTreeSet::new();
        for func in &self.module.funcs {
            for op in &func.body {
                if let Op::CallIndirect { type_index } = op {
                    signatures.insert(*type_index);
                }
            }
        }
        // A trampoline dispatches through the table too, and its signature may
        // appear in no `call_indirect` at all.
        for invoke in &self.analysis.invokes {
            signatures.insert(invoke.callee_type);
        }
        // A thread's start routine is reached the same way, and in a module
        // that only ever starts threads there is no `call_indirect` of that
        // shape anywhere.
        if let Some(spawn) = self.analysis.spawn {
            signatures.insert(spawn.entry_type);
        }
        // And everything the table holds, so anything reachable through it can
        // be called from outside as well. That is what an embind registration
        // is: a table index, and a host with no other way to reach it.
        // The cost is one arm per table entry, wherever it lands.
        for func in self.analysis.table.values() {
            if let Some(index) = crate::analysis::type_index_of(self.module, *func) {
                signatures.insert(index);
            }
        }
        self.invoke_by_slot(&signatures);
        for type_index in signatures {
            let ty = self.module.types.get(type_index as usize).ok_or_else(|| {
                Error::invalid("call_indirect names a missing type", "type section")
            })?;
            let args: Vec<String> = (0..ty.params.len()).map(|at| format!("p{at}")).collect();
            let _ = writeln!(
                self.out,
                "    pub(crate) fn call_indirect_{type_index}(&mut self, index: i32{}) {} {{\n        match self.table.get(index as u32 as usize).copied() {{",
                signature_of(ty),
                return_type(ty)
            );
            let import_count = self.module.func_imports.len() as u32;
            for (at, func) in self.module.funcs.iter().enumerate() {
                if func.type_index != type_index {
                    continue;
                }
                let index = import_count + at as u32;
                let _ = writeln!(
                    self.out,
                    "            Some({index}) => self.{}({}),",
                    function_ident_with(index, &self.analysis, &self.recognised),
                    args.join(", ")
                );
            }
            for (index, import) in self.module.func_imports.iter().enumerate() {
                if import.type_index != type_index {
                    continue;
                }
                let _ = writeln!(
                    self.out,
                    "            Some({index}) => self.f{index}({}),",
                    args.join(", ")
                );
            }
            self.out.push_str(concat!(
                "            Some(u32::MAX) | None => rt::trap(\"uninitialized element\"),\n",
                "            Some(_) => rt::trap(\"indirect call type mismatch\"),\n",
                "        }\n    }\n\n",
            ));
        }
        Ok(())
    }

    /// Who reaches this function, and what it reaches.
    ///
    /// The direction that matters is upwards: a call site says what it calls,
    /// and nothing in the module says what calls *this*. A function with no
    /// direct callers at all is worth saying so about — it is either an entry
    /// point, something only the table reaches, or dead.
    fn cross_reference(&self, index: u32, slots: &[u32]) -> String {
        const NAMED: usize = 6;
        let graph = &self.analysis.call_graph;
        let callers = graph.callers_of(index);
        let calls = graph.calls_from(index);
        let mut out = String::new();

        if callers.is_empty() {
            let exported = self
                .module
                .exports
                .iter()
                .any(|export| export.kind == ExportKind::Func && export.index == index);
            let reached = if exported {
                "it is exported"
            } else if slots.is_empty() {
                "nothing in this module reaches it — an entry point, or dead"
            } else {
                "the table reaches it"
            };
            let _ = writeln!(out, "    ///\n    /// No direct callers: {reached}.");
        } else {
            let named: Vec<String> = callers
                .iter()
                .take(NAMED)
                .map(|caller| {
                    format!(
                        "`{}`",
                        function_ident_with(*caller, &self.analysis, &self.recognised)
                    )
                })
                .collect();
            // The site count, not just the caller count: one caller that
            // calls this from a loop body is one caller and many sites, and
            // instrumenting the body measures whichever site happened to run.
            let sites = self.analysis.call_graph.sites_reaching(index);
            let from_sites = if sites == callers.len() {
                String::new()
            } else {
                format!(", from {sites} call sites")
            };
            let _ = writeln!(
                out,
                "    ///\n    /// Called by {}: {}{}{from_sites}.",
                callers.len(),
                named.join(", "),
                if callers.len() > NAMED { ", …" } else { "" }
            );
        }

        let indirect = self.analysis.call_graph.calls_indirectly.get(&index);
        if !calls.is_empty() || indirect.is_some() {
            let named: Vec<String> = calls
                .iter()
                .take(NAMED)
                .map(|callee| {
                    format!(
                        "`{}`",
                        function_ident_with(*callee, &self.analysis, &self.recognised)
                    )
                })
                .collect();
            let through_the_table = indirect
                .map(|types| {
                    format!(
                        ", and through the table: {}",
                        types
                            .iter()
                            .map(|ty| self
                                .module
                                .types
                                .get(*ty as usize)
                                .map_or_else(|| format!("type {ty}"), signature_text))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                })
                .unwrap_or_default();
            let _ = writeln!(
                out,
                "    /// Calls {}{}{}{}{through_the_table}.",
                calls.len(),
                if named.is_empty() { "" } else { ": " },
                named.join(", "),
                if calls.len() > NAMED { ", …" } else { "" }
            );
        }
        out
    }

    /// One function, as text.
    ///
    /// Returned rather than written straight out, because under a split layout
    /// it belongs in a part file rather than in `mod.rs`.
    fn function(&mut self, index: u32, func: &Func) -> Result<String> {
        let ty = self
            .module
            .types
            .get(func.type_index as usize)
            .ok_or_else(|| {
                Error::invalid(
                    "function refers to a missing type",
                    format!("function #{index}"),
                )
            })?;
        if ty.results.len() > 1 {
            return Err(Error::unsupported(
                "multiple return values",
                format!("function #{index}"),
            ));
        }

        let mut out = String::new();
        if let Some(name) = self.module.func_name(index) {
            let _ = writeln!(out, "    /// `{}`", escape_doc(name));
        } else if let Some(name) = self.recognised.get(&index) {
            // Recognised by its shape, not by anything the module said. The
            // catalogue is only as good as the toolchain it came from, so the
            // comment says where the name is from.
            let _ = writeln!(
                out,
                "    /// Function #{index}, recognised as `{}`: its body fingerprints\n    /// identically to that function in the signature catalogue.",
                escape_doc(name)
            );
        } else if let Some(derived) = self.analysis.derived_names.get(&index) {
            // The name is a guess, so the reason travels with it. Without the
            // evidence a reader has to take `parse_xmpp_offer` on trust, and
            // there is nothing else in a stripped module to check it against.
            match derived.source {
                crate::analysis::NameSource::Assert => {
                    let _ = writeln!(
                        out,
                        "    /// Function #{index}, named `{}` by its own `__assert_fail`: the\n    /// last argument of that call is `__func__`, so this is the compiler\n    /// writing the name down rather than anything guessing at it.",
                        escape_doc(&derived.name)
                    );
                }
                crate::analysis::NameSource::Message { references, unique } => {
                    let shared = if unique {
                        "and no other function references it".to_string()
                    } else {
                        "though other functions reference it too — inlining spreads a\n    /// message across everything it was inlined into".to_string()
                    };
                    let _ = writeln!(
                        out,
                        "    /// Function #{index}. The module names nothing; this one references\n    /// {}\n    /// {references} time(s), {shared} — so it is probably `{}`.",
                        escape_comment(&derived.evidence),
                        escape_doc(&derived.name)
                    );
                }
            }
            if !derived.rejected.is_empty() {
                // What else it could have been. A function assembled out of
                // several inlined ones references all of their messages, and
                // seeing the runners-up is what stops a reader trusting the
                // winner more than it deserves.
                let _ = writeln!(
                    out,
                    "    /// Other candidates, in order: {}.",
                    derived
                        .rejected
                        .iter()
                        .map(|name| format!("`{}`", escape_doc(name)))
                        .collect::<Vec<_>>()
                        .join(", ")
                );
            }
        } else {
            let _ = writeln!(out, "    /// Function #{index}, unnamed in the module.");
        }
        // Where a `call_indirect` would find it. The table index is not the
        // function index, and the difference is what stands between reading a
        // call site and knowing what it calls.
        let slots: Vec<u32> = self
            .analysis
            .table
            .iter()
            .filter(|(_, func)| **func == index)
            .map(|(slot, _)| *slot)
            .collect();
        if !slots.is_empty() {
            let _ = writeln!(
                out,
                "    ///\n    /// In the function table at slot{} {} — this is what a\n    /// `call_indirect` with that index reaches.",
                if slots.len() == 1 { "" } else { "s" },
                slots
                    .iter()
                    .map(u32::to_string)
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }

        out.push_str(&self.cross_reference(index, &slots));

        let frame = self.analysis.frames.get(&index);
        if let Some(frame) = frame {
            out.push_str(&frame_summary(frame));
        }
        // `pub(crate)` rather than private: under a split layout the callers
        // live in sibling modules, and a private method would be visible only
        // in the one it was defined in.
        let _ = writeln!(
            out,
            "    pub(crate) fn {}(&mut self{}) {} {{",
            function_ident_with(index, &self.analysis, &self.recognised),
            signature_of(ty),
            return_type(ty)
        );

        let asked_for = self.only.as_ref().is_none_or(|only| only.contains(&index));
        if asked_for {
            // The body's lines start after everything written above.
            let before_body = out.matches('\n').count();
            let context = Context {
                module: self.module,
                analysis: &self.analysis,
                recognised: &self.recognised,
                instrument: self.instrument,
                map_offsets: self.map_offsets,
            };
            let (body, spans) = Body::new(context, func, ty, index).emit()?;
            out.push_str(&body);
            if self.map_offsets {
                self.spans.push((index, before_body, spans));
            }
        } else {
            // Not decompiled, and saying so rather than looking decompiled. The
            // signature and the name stay, so callers still compile and the
            // index still finds it.
            let _ = writeln!(
                out,
                "        unimplemented!(\"function #{index} was not decompiled: --only\")"
            );
        }
        out.push_str("    }\n\n");
        Ok(out)
    }
}

/// One generated line and the wasm bytes behind it: `(line, offset, length)`.
///
/// The line is relative to whatever produced it — a body on its own, until the
/// generator places the function and makes it absolute.
type LineSpan = (usize, u32, u32);

/// A function's contribution to the offset map: its index, how many lines of
/// its chunk come before its body, and the body's own spans.
type FunctionSpans = (u32, usize, Vec<LineSpan>);

/// What every function body is given and none of them changes.
///
/// A struct because there are five of them and they travel together; passing
/// them one by one is how a constructor ends up with eight parameters in
/// which two `bool`s sit next to each other waiting to be swapped.
#[derive(Clone, Copy)]
struct Context<'a> {
    module: &'a Module,
    analysis: &'a Analysis,
    recognised: &'a std::collections::BTreeMap<u32, String>,
    instrument: bool,
    map_offsets: bool,
}

/// A value sitting on the operand stack, and how it may be used.
#[derive(Debug, Clone)]
struct Value {
    code: String,
    ty: ValType,
    /// Whether this is an expression waiting to be inlined into its consumer
    /// rather than a name that already exists.
    ///
    /// A `let` binding is not folded: nothing can change what it holds, so it
    /// never needs spilling, and re-spilling one produced 36269 lines of
    /// `let t5: i32 = t4;` in the VoIP module.
    folded: bool,
    /// What a folded expression reads, and therefore what can invalidate it.
    reads: Reads,
}

/// What an expression on the stack depends on.
///
/// Only these two, because only pure expressions are ever folded: a load is
/// impure and gets a name, so a folded value never reads memory. Which means
/// a store, a `memory.fill` or a `memory.grow` cannot invalidate anything on
/// the stack, and the spill before them was pure cost.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
struct Reads {
    /// Which locals, by index, as a bitset. A local is a Rust `let mut`, and
    /// only `local.set` and `local.tee` on *that* index can change it — not a
    /// call, which cannot reach this function's locals at all.
    locals: u64,
    /// A local past the 64th, which the bitset has no room for. Rare enough
    /// that a conservative "any high local invalidates this" costs nothing.
    high_local: bool,
    /// A global, which a call *can* change, since the callee may set it.
    globals: bool,
}

impl Reads {
    /// A read of one local.
    fn local(index: u32) -> Self {
        Self {
            locals: if index < 64 { 1 << index } else { 0 },
            high_local: index >= 64,
            globals: false,
        }
    }

    /// A read of a global.
    fn global() -> Self {
        Self {
            locals: 0,
            high_local: false,
            globals: true,
        }
    }

    /// What both operands read.
    fn and(self, other: Self) -> Self {
        Self {
            locals: self.locals | other.locals,
            high_local: self.high_local || other.high_local,
            globals: self.globals || other.globals,
        }
    }

    /// Whether a write to this local changes what this expression reads.
    fn touched_by_local(self, index: u32) -> bool {
        if index < 64 {
            self.locals & (1 << index) != 0
        } else {
            self.high_local
        }
    }

    /// Whether a call can change what this reads.
    fn survives_a_call(self) -> bool {
        !self.globals
    }
}

impl Value {
    /// The code, parenthesised unless it plainly does not need to be.
    ///
    /// Folding puts expressions inside other expressions, and Rust's
    /// precedence is not wasm's: `a + b` folded into `{0} as u32` gives
    /// `a + b as u32`, which casts `b` and adds it to `a`. The template cannot
    /// know whether its operand is compound, so the operand answers for
    /// itself — and answers conservatively, since a redundant pair of brackets
    /// costs nothing and a missing pair is a wrong number.
    fn as_operand(&self) -> String {
        if is_atomic(&self.code) {
            self.code.clone()
        } else {
            format!("({})", self.code)
        }
    }
}

/// Whether an expression can sit inside another without brackets.
///
/// The question is only about precedence, so it is answered by looking for an
/// operator *outside* any brackets: `l0.wrapping_sub(2i32)` has none and binds
/// tighter than anything it could be folded into, while `l1 as u32` has one and
/// would bind the wrong way inside `{0} as i64`.
///
/// Anything not understood is treated as compound. A redundant pair of brackets
/// costs a little noise; a missing pair costs a wrong number.
fn is_atomic(code: &str) -> bool {
    let bytes = code.as_bytes();
    let mut depth = 0usize;
    let mut at = 0usize;
    while at < bytes.len() {
        match bytes[at] {
            b'(' | b'[' => depth += 1,
            b')' | b']' => depth = depth.saturating_sub(1),
            // An operator at the top level means the expression is compound.
            b'+' | b'-' | b'*' | b'/' | b'%' | b'&' | b'|' | b'^' | b'<' | b'>' | b'=' | b'!'
            | b'?' | b',' | b'{' | b'}'
                if depth == 0 =>
            {
                return false;
            }
            // `as`, which is why a cast needs brackets inside another cast.
            b'a' if depth == 0 && code[at..].starts_with("as ") => return false,
            b' ' if depth == 0 => return false,
            _ => {}
        }
        at += 1;
    }
    true
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum FrameKind {
    Block,
    Loop,
    If,
}

#[derive(Debug)]
struct Frame {
    kind: FrameKind,
    label: usize,
    result: Option<ValType>,
    /// Height the value stack returns to when the frame closes.
    stack_height: usize,
    /// Set once the frame's code becomes unreachable, so the rest of it is
    /// dropped rather than emitted — wasm's stack is polymorphic after a
    /// branch, and Rust's type checker is not.
    unreachable: bool,
    /// An `if` that has seen its `else`.
    in_else: bool,
}

struct Body<'a> {
    module: &'a Module,
    analysis: &'a Analysis,
    /// Names a signature catalogue recognised, so a call site spells the callee
    /// the same way its definition does.
    recognised: &'a std::collections::BTreeMap<u32, String>,
    /// Whether writes report themselves to a watchpoint.
    instrument: bool,
    /// For each emitted line that came from the body, the span of wasm bytes
    /// that produced it: `(line index in this body, offset, length)`.
    ///
    /// Only collected when asked for. A line covers every operator lowered
    /// since the previous line, so a folded operand is inside the span of the
    /// line that consumed it rather than missing from the map.
    spans: Vec<LineSpan>,
    /// Whether to collect them at all.
    map_offsets: bool,
    /// The offset of the first operator not yet attributed to a line.
    pending: Option<u32>,
    /// Lines emitted so far, kept rather than counted.
    lines: usize,
    /// Where the operator being lowered sits in the wasm file, or 0 if the
    /// decoder did not record it.
    here: u32,
    /// This function's C stack frame, when it has one.
    frame: Option<&'a StackFrame>,
    func: &'a Func,
    ty: &'a crate::module::FuncType,
    index: u32,
    out: String,
    stack: Vec<Value>,
    frames: Vec<Frame>,
    temps: usize,
    labels: usize,
    depth: usize,
    unreachable: bool,
    /// Nesting still to be skipped while unreachable.
    skipping: usize,
    /// The instruction after the one being emitted, for the one lookahead this
    /// backend does.
    next_op: Option<Op>,
}

impl<'a> Body<'a> {
    fn new(
        context: Context<'a>,
        func: &'a Func,
        ty: &'a crate::module::FuncType,
        index: u32,
    ) -> Self {
        let Context {
            module,
            analysis,
            recognised,
            instrument,
            map_offsets,
        } = context;
        Self {
            module,
            analysis,
            recognised,
            instrument,
            spans: Vec::new(),
            map_offsets,
            pending: None,
            lines: 0,
            here: 0,
            frame: analysis.frames.get(&index),
            func,
            ty,
            index,
            out: String::new(),
            stack: Vec::new(),
            frames: Vec::new(),
            temps: 0,
            labels: 0,
            depth: 2,
            unreachable: false,
            skipping: 0,
            next_op: None,
        }
    }

    fn location(&self) -> String {
        format!("function #{}", self.index)
    }

    /// The opening of a call to a memory write: `store32(` normally, and
    /// `store32_at(7, ` when the output is instrumented.
    ///
    /// The site is the function index, which is what `names.json` looks a
    /// function up by. Every write goes through this, `memory.fill` included —
    /// a `memset` is the usual answer to "who zeroed this address", and it is
    /// not a store.
    fn write_call(&self, method: &str) -> String {
        if self.instrument {
            // The function *and* the instruction. The function alone answers
            // "who wrote this address"; a function with fifty stores in it
            // leaves the next question open, and the offset closes it —
            // `unwasm bytes <module> <offset> <len>` prints exactly the store
            // that fired.
            format!("{method}_at({}, {}, ", self.index, self.here)
        } else {
            format!("{method}(")
        }
    }

    /// Emits the body, and the line-to-bytes map when one was asked for.
    fn emit(mut self) -> Result<(String, Vec<LineSpan>)> {
        // Parameters arrive as `p0..`, locals are declared zeroed, and both are
        // rebound as `l0..` so that `local.set` on a parameter is the same
        // statement as `local.set` on a local.
        for (at, param) in self.ty.params.iter().enumerate() {
            self.line(&format!(
                "let mut {}: {} = p{at};",
                self.local_ident(at as u32),
                param.rust_name()
            ));
        }
        for (at, local) in self.func.locals.iter().enumerate() {
            let at = self.ty.params.len() + at;
            self.line(&format!(
                "let mut {}: {} = {};",
                self.local_ident(at as u32),
                local.rust_name(),
                local.zero()
            ));
        }

        let body = self.func.body.clone();
        for (at, op) in body.iter().enumerate() {
            // The next instruction is worth having for one reason: a Rust
            // string is `i32.const ptr; i32.const len`, and the length is what
            // stops the text from running into the next string.
            self.next_op = body.get(at + 1).cloned();
            let before = self.emitted_lines();
            let span = self.func.offsets.get(at).copied();
            self.here = span.map_or(0, |(offset, _)| offset);
            if self.map_offsets && self.pending.is_none() {
                self.pending = span.map(|(offset, _)| offset);
            }
            self.op(op)?;
            if self.map_offsets && self.emitted_lines() > before {
                if let (Some(start), Some((offset, length))) = (self.pending, span) {
                    self.spans.push((before, start, offset + length - start));
                }
                self.pending = None;
            }
        }

        // The function's own result. If control cannot reach here the module
        // already ended in a branch or a trap, and Rust still needs an
        // expression of the right type: `rt::trap` returns `!`, so it fits any.
        if self.unreachable {
            self.line("rt::trap(\"unreachable code reached\")");
        } else if self.ty.results.is_empty() {
            // Nothing to return; anything left on the stack is dropped, as the
            // implicit return does.
        } else {
            let value = self.pop()?;
            self.line(&value.code);
        }
        Ok((self.out, self.spans))
    }

    /// How many lines have been emitted so far.
    ///
    /// Counted as they go rather than by scanning the output: this is asked
    /// once per operator, and a 100k-line function whose every operator
    /// re-counted the whole buffer turned a three-second decompile into one
    /// that had not finished after ten minutes.
    fn emitted_lines(&self) -> usize {
        self.lines
    }

    /// How deep the indentation is allowed to get.
    ///
    /// Past this the leading whitespace stops growing, and the nesting is read
    /// from the labels instead — which is where it is legible at that depth
    /// anyway. This is not tidiness: a `br_table` dispatch in the VoIP module
    /// nests **1991** blocks, so a line inside it carried 7964 spaces, and one
    /// part file came to 650 MB of which **644 MB was indentation**. The whole
    /// module was 1.8 GB. Capped, that is a 20th of the bytes, for output that
    /// differs only in the whitespace nobody could have used.
    const MAX_INDENT: usize = 32;

    fn line(&mut self, text: &str) {
        self.lines += 1;
        for _ in 0..self.depth.min(Self::MAX_INDENT) {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn push(&mut self, code: String, ty: ValType, folded: bool, reads: Reads) {
        self.stack.push(Value {
            code,
            ty,
            folded,
            reads,
        });
    }

    /// How long an expression may get before it is given a name instead.
    ///
    /// wasm's stack consumes each value exactly once, so folding an expression
    /// into its consumer never duplicates work — but it does nest, and nesting
    /// without a limit turns a long chain of arithmetic into one unreadable
    /// line. This is where a line stops being easier to read than two.
    const FOLD_LIMIT: usize = 100;

    /// Pushes a computed value, naming it first.
    ///
    /// Anything that can trap or that touches state goes through here: naming
    /// it is what makes it *happen*, at the point the module says it happens.
    fn push_temp(&mut self, code: &str, ty: ValType) {
        let name = format!("t{}", self.temps);
        self.temps += 1;
        self.line(&format!("let {name}: {} = {code};", ty.rust_name()));
        // Not folded: it is a binding, and nothing can change what it holds.
        self.push(name, ty, false, Reads::default());
    }

    /// Pushes an expression that can be folded into whatever consumes it.
    ///
    /// Only for expressions that cannot trap and touch nothing: `a + b` used
    /// once reads better inline than as a `let` two lines up, and one function
    /// in the VoIP module spends 171704 of its 453292 lines on bindings of
    /// exactly that kind.
    ///
    /// Purity is the whole condition, and the reason is `drop`. A folded value
    /// that is dropped is never emitted at all — so folding a division would
    /// lose the trap it owes on a zero divisor, and folding an atomic
    /// read-modify-write would lose the write. The differential tests caught
    /// both within a minute of the first attempt, which is what they are for.
    fn push_pure(&mut self, code: &str, ty: ValType, reads: Reads) {
        if code.len() <= Self::FOLD_LIMIT {
            self.push(code.to_string(), ty, true, reads);
        } else {
            self.push_temp(code, ty);
        }
    }

    fn pop(&mut self) -> Result<Value> {
        self.stack
            .pop()
            .ok_or_else(|| Error::invalid("operand stack underflow", self.location()))
    }

    fn pop_n(&mut self, count: usize) -> Result<Vec<Value>> {
        let mut values = Vec::with_capacity(count);
        for _ in 0..count {
            values.push(self.pop()?);
        }
        values.reverse();
        Ok(values)
    }

    /// Names everything still on the stack.
    ///
    /// Called before anything that can change what a folded value reads — a
    /// write to a local or global, a store, a call. Without it, a folded
    /// `local.get 0` pushed before `local.set 0` would read the new value, and
    /// the output would be wrong in a way that only shows up on some inputs.
    /// Names everything on the stack, whatever it reads.
    ///
    /// For opening a block, where the reason is scope rather than change: a
    /// value spilled inside a block and consumed after it would name a binding
    /// that has gone out of scope.
    fn spill_stack(&mut self) {
        self.spill_if(|_| true);
    }

    /// Names the values a call could invalidate.
    ///
    /// A callee can set a global. It cannot reach this function's locals,
    /// which are Rust `let mut` bindings — so `frame` folded into an
    /// expression survives a call, and spilling it was pure cost: 47427 lines
    /// of `let tN: i32 = frame;` in the VoIP module.
    fn spill_across_a_call(&mut self) {
        self.spill_if(|reads| !reads.survives_a_call());
    }

    /// Names the values a write to this local could invalidate.
    ///
    /// By index, not "anything that reads a local": `frame` folded into an
    /// expression is not invalidated by a write to `l5`, and treating every
    /// local as one produced 47427 lines of `let tN: i32 = frame;` in the VoIP
    /// module.
    fn spill_across_a_local_write(&mut self, index: u32) {
        self.spill_if(|reads| reads.touched_by_local(index));
    }

    /// Names the values a write to a global could invalidate.
    fn spill_across_a_global_write(&mut self) {
        self.spill_if(|reads| reads.globals);
    }

    fn spill_if(&mut self, invalidated: impl Fn(Reads) -> bool) {
        for at in 0..self.stack.len() {
            if !self.stack[at].folded || !invalidated(self.stack[at].reads) {
                continue;
            }
            let value = self.stack[at].clone();
            let name = format!("t{}", self.temps);
            self.temps += 1;
            self.line(&format!(
                "let {name}: {} = {};",
                value.ty.rust_name(),
                value.code
            ));
            self.stack[at] = Value {
                code: name,
                ty: value.ty,
                folded: false,
                reads: Reads::default(),
            };
        }
    }

    /// Names the given operands, for a call whose receiver is `&mut self`.
    ///
    /// `self.f1(self.f2())` does not borrow-check, and neither does a store
    /// whose value comes from a call. Naming the operands first sidesteps the
    /// whole question instead of relying on two-phase borrows to cover it.
    ///
    /// Only operands that mention `self` need it. An expression over locals —
    /// which is most of them — borrows nothing and can stay where it is, and
    /// leaving it there is most of what folding is worth: every argument of
    /// every call and store would otherwise be named.
    fn spill_operands(&mut self, values: &mut [Value]) {
        for value in values.iter_mut() {
            if !value.code.contains("self.") {
                continue;
            }
            let name = format!("t{}", self.temps);
            self.temps += 1;
            self.line(&format!(
                "let {name}: {} = {};",
                value.ty.rust_name(),
                value.code
            ));
            value.code = name;
            value.folded = false;
        }
    }

    fn block_result(&self, ty: BlockType) -> Result<Option<ValType>> {
        Ok(match ty {
            BlockType::Empty => None,
            BlockType::Value(value) => Some(value),
            BlockType::Func(index) => {
                let signature =
                    self.module.types.get(index as usize).ok_or_else(|| {
                        Error::invalid("block names a missing type", self.location())
                    })?;
                if !signature.params.is_empty() {
                    return Err(Error::unsupported(
                        "block with parameters (multi-value)",
                        self.location(),
                    ));
                }
                match signature.results.len() {
                    0 => None,
                    1 => Some(signature.results[0]),
                    _ => {
                        return Err(Error::unsupported(
                            "block with several results (multi-value)",
                            self.location(),
                        ));
                    }
                }
            }
        })
    }

    /// Opens a frame, declaring its result variable first so that every exit
    /// from the block assigns it rather than carrying a value out.
    fn open(&mut self, kind: FrameKind, ty: BlockType, condition: Option<Value>) -> Result<()> {
        let result = self.block_result(ty)?;
        // Everything already on the stack is named *before* the block opens.
        //
        // wasm's operand stack survives a block boundary and Rust's scopes do
        // not: a value spilled inside the block and consumed after it would
        // name a `let` that has gone out of scope. Spilling out here puts those
        // bindings in the enclosing scope, where both uses can see them. This
        // was not theoretical — it was the first thing a real 236 KiB module
        // hit, in three separate functions.
        self.spill_stack();
        let label = self.labels;
        self.labels += 1;
        if let Some(result) = result {
            self.line(&format!(
                "let mut r{label}: {} = {};",
                result.rust_name(),
                result.zero()
            ));
        }
        match kind {
            FrameKind::Block => self.line(&format!("'b{label}: {{")),
            FrameKind::Loop => self.line(&format!("'b{label}: loop {{")),
            FrameKind::If => {
                let condition = condition.expect("an if frame always has a condition");
                self.line(&format!("'b{label}: {{ if {} != 0 {{", condition.code));
            }
        }
        self.frames.push(Frame {
            kind,
            label,
            result,
            stack_height: self.stack.len(),
            unreachable: false,
            in_else: false,
        });
        self.depth += 1;
        Ok(())
    }

    /// Emits the assignment and jump for a branch to `depth`.
    fn branch(&mut self, depth: u32) -> Result<()> {
        let at = self
            .frames
            .len()
            .checked_sub(depth as usize + 1)
            .ok_or_else(|| Error::invalid("branch past the outermost block", self.location()))?;
        let frame_kind = self.frames[at].kind;
        let frame_label = self.frames[at].label;
        let frame_result = self.frames[at].result;

        // A branch to a loop restarts it, and the loop's parameters (none, at
        // this level) are what it would carry. A branch to a block or an `if`
        // leaves it, carrying the block's result.
        let statement = if frame_kind == FrameKind::Loop {
            format!("continue 'b{frame_label};")
        } else {
            if let Some(ty) = frame_result {
                let value = self.stack.last().cloned().ok_or_else(|| {
                    Error::invalid("branch with no result value", self.location())
                })?;
                let _ = ty;
                self.line(&format!("r{frame_label} = {};", value.code));
            }
            format!("break 'b{frame_label};")
        };
        self.line(&statement);
        Ok(())
    }

    fn go_unreachable(&mut self) {
        self.unreachable = true;
        if let Some(frame) = self.frames.last_mut() {
            frame.unreachable = true;
        }
        let height = self.frames.last().map_or(0, |frame| frame.stack_height);
        self.stack.truncate(height);
    }

    #[allow(
        clippy::too_many_lines,
        reason = "one arm per opcode class; splitting it would hide the dispatch"
    )]
    fn op(&mut self, op: &Op) -> Result<()> {
        // While unreachable, instructions still nest, so the skip has to track
        // depth to know which `end` closes the frame it is inside.
        if self.unreachable {
            match op {
                Op::Block(_) | Op::Loop(_) | Op::If(_) => {
                    self.skipping += 1;
                    return Ok(());
                }
                Op::End | Op::Else if self.skipping > 0 => {
                    if matches!(op, Op::End) {
                        self.skipping -= 1;
                    }
                    return Ok(());
                }
                Op::End | Op::Else => {}
                _ => return Ok(()),
            }
        }

        match op {
            Op::Unreachable => {
                self.line("rt::trap(\"unreachable\");");
                self.go_unreachable();
            }
            Op::Nop => {}
            Op::Block(ty) => self.open(FrameKind::Block, *ty, None)?,
            Op::Loop(ty) => self.open(FrameKind::Loop, *ty, None)?,
            Op::If(ty) => {
                let condition = self.pop()?;
                self.open(FrameKind::If, *ty, Some(condition))?;
            }
            Op::Else => self.emit_else()?,
            Op::End => self.emit_end()?,
            Op::Br(depth) => {
                self.branch(*depth)?;
                self.go_unreachable();
            }
            Op::BrIf(depth) => {
                let condition = self.pop()?;
                self.line(&format!("if {} != 0 {{", condition.code));
                self.depth += 1;
                self.branch(*depth)?;
                self.depth -= 1;
                self.line("}");
            }
            Op::BrTable { targets, default } => {
                let index = self.pop()?;
                self.line(&format!("match {} as u32 {{", index.code));
                self.depth += 1;
                for (at, target) in targets.iter().enumerate() {
                    self.line(&format!("{at} => {{"));
                    self.depth += 1;
                    self.branch(*target)?;
                    self.depth -= 1;
                    self.line("}");
                }
                self.line("_ => {");
                self.depth += 1;
                self.branch(*default)?;
                self.depth -= 1;
                self.line("}");
                self.depth -= 1;
                self.line("}");
                self.go_unreachable();
            }
            Op::Return => {
                if self.ty.results.is_empty() {
                    self.line("return;");
                } else {
                    let value = self.pop()?;
                    self.line(&format!("return {};", value.code));
                }
                self.go_unreachable();
            }
            Op::Call(index) => self.emit_call(*index)?,
            Op::CallIndirect { type_index } => self.emit_call_indirect(*type_index)?,
            Op::Drop => {
                self.pop()?;
            }
            Op::Select => {
                let condition = self.pop()?;
                let alternative = self.pop()?;
                let consequent = self.pop()?;
                let ty = consequent.ty;
                let reads = condition.reads.and(consequent.reads).and(alternative.reads);
                self.push_pure(
                    &format!(
                        "if {} != 0 {{ {} }} else {{ {} }}",
                        condition.code, consequent.code, alternative.code
                    ),
                    ty,
                    reads,
                );
            }
            Op::LocalGet(index) => {
                let ty = self.local_type(*index)?;
                self.push(self.local_ident(*index), ty, true, Reads::local(*index));
            }
            Op::LocalSet(index) => {
                let value = self.pop()?;
                self.spill_across_a_local_write(*index);
                self.line(&format!("{} = {};", self.local_ident(*index), value.code));
            }
            Op::LocalTee(index) => {
                let value = self.pop()?;
                self.spill_across_a_local_write(*index);
                self.line(&format!("{} = {};", self.local_ident(*index), value.code));
                let ty = self.local_type(*index)?;
                self.push(self.local_ident(*index), ty, true, Reads::local(*index));
            }
            Op::GlobalGet(index) => {
                let ty = self.global_type(*index)?;
                self.push(
                    format!("self.{}", global_ident(*index, self.analysis)),
                    ty,
                    true,
                    Reads::global(),
                );
            }
            Op::GlobalSet(index) => {
                let value = self.pop()?;
                self.spill_across_a_global_write();
                self.line(&format!(
                    "self.{} = {};",
                    global_ident(*index, self.analysis),
                    value.code
                ));
            }
            Op::I32Const(value) => {
                // A constant that addresses a static string is quoted inline.
                // On a minified module these are often the only readable thing
                // left, and they cost nothing to carry: the comment travels
                // with the expression into whatever consumes it.
                let placements = &self.analysis.placements;
                let text = match self.next_op {
                    // `ptr, len`: the pair a `&str` is passed as. Trying the
                    // length first is what keeps Rust's unterminated strings
                    // from running into each other.
                    Some(Op::I32Const(length)) if length > 0 && length <= 512 => {
                        analysis::placed_text(self.module, placements, *value, Some(length as u32))
                            .or_else(|| {
                                analysis::placed_text(self.module, placements, *value, None)
                            })
                    }
                    _ => analysis::placed_text(self.module, placements, *value, None),
                };
                let code = match text {
                    Some(text) => format!("{} /* {} */", format_i32(*value), escape_comment(&text)),
                    // Not text, but shared: a bare number that dozens of
                    // functions reference is state they have in common, and
                    // saying how many is what makes that visible at the call
                    // site rather than only in aggregate.
                    None => match self.analysis.hot_addresses.get(value) {
                        Some(functions) => {
                            format!(
                                "{} /* address, in {functions} functions */",
                                format_i32(*value)
                            )
                        }
                        None => format_i32(*value),
                    },
                };
                self.push(code, ValType::I32, true, Reads::default());
            }
            Op::I64Const(value) => {
                self.push(format_i64(*value), ValType::I64, true, Reads::default())
            }
            Op::F32Const(value) => {
                self.push(format_f32(*value), ValType::F32, true, Reads::default())
            }
            Op::F64Const(value) => {
                self.push(format_f64(*value), ValType::F64, true, Reads::default())
            }
            Op::Load { kind, mem } => {
                let address = self.pop()?;
                let method = load_method(*kind);
                self.push_temp(
                    &format!("self.memory.{method}({}, {})", address.code, mem.offset),
                    kind.result(),
                );
            }
            Op::Store { kind, mem } => {
                let mut values = self.pop_n(2)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                let (method, cast) = store_method(*kind);
                let call = self.write_call(method);
                self.line(&format!(
                    "self.memory.{call}{}, {}, {}{cast});",
                    values[0].code, mem.offset, values[1].code
                ));
            }
            Op::MemorySize => self.push_temp("self.memory.size()", ValType::I32),
            Op::MemoryGrow => {
                let mut values = self.pop_n(1)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                self.push_temp(
                    &format!("self.memory.grow({} as u32)", values[0].code),
                    ValType::I32,
                );
            }
            Op::MemoryFill => {
                let mut values = self.pop_n(3)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                let call = self.write_call("fill");
                self.line(&format!(
                    "self.memory.{call}{}, {}, {});",
                    values[0].code, values[1].code, values[2].code
                ));
            }
            Op::MemoryCopy => {
                let mut values = self.pop_n(3)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                let call = self.write_call("copy");
                self.line(&format!(
                    "self.memory.{call}{}, {}, {});",
                    values[0].code, values[1].code, values[2].code
                ));
            }
            Op::MemoryInit(segment) => {
                let mut values = self.pop_n(3)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                // A dropped segment is an empty one, not a missing one: a
                // zero-length `memory.init` from it still succeeds, and any
                // other length is out of bounds. Reading `data_dropped` into a
                // binding first also keeps the borrow off `self.memory`.
                self.line(&format!(
                    "let segment: &[u8] = if self.data_dropped[{segment}] {{ &[] }} else {{ DATA_{segment} }};"
                ));
                let call = self.write_call("init");
                self.line(&format!(
                    "self.memory.{call}{}, segment, {}, {});",
                    values[0].code, values[1].code, values[2].code
                ));
            }
            Op::DataDrop(segment) => {
                // Dropping is observable, which is easy to talk yourself out of:
                // the bytes are a `const` here, so there is nothing to free. But
                // a later `memory.init` from a dropped segment traps in every
                // engine, and a decompilation that kept returning data would
                // disagree on exactly that call.
                self.line(&format!("self.data_dropped[{segment}] = true;"));
            }
            Op::Atomic { op: atomic, mem } => self.emit_atomic(*atomic, mem.offset)?,
            Op::AtomicFence => {
                // Under one thread there is nothing to order and this compiles
                // to nothing. Under several it is the instruction's whole
                // point: the plain accesses either side of it are relaxed
                // atomics on a shared memory, and dropping the fence lets a
                // reader see them in an order the guest excluded.
                self.line("rt::fence();");
            }
            Op::Num(num) => self.emit_num(*num)?,
        }
        Ok(())
    }

    /// Emits one atomic instruction.
    ///
    /// Under a single thread the arithmetic is the plain arithmetic; what the
    /// runtime adds is the alignment check, which an atomic has and its plain
    /// counterpart does not. The two blocking instructions are the only place
    /// the thread count is observable, and they are handled there.
    fn emit_atomic(&mut self, atomic: crate::module::Atomic, offset: u64) -> Result<()> {
        use crate::module::AtomicKind;

        let width = atomic.width;
        let result = atomic.ty;
        // An i64 operation's values are i64; an i32's are i32 and go through
        // the runtime's i64 interface, which is why each one casts on the way
        // in and on the way out.
        let cast_in = if result == ValType::I32 {
            " as i64"
        } else {
            ""
        };
        let cast_out = if result == ValType::I32 {
            " as i32"
        } else {
            ""
        };

        match atomic.kind {
            AtomicKind::Load => {
                let address = self.pop()?;
                self.push_temp(
                    &format!(
                        "self.memory.atomic_load({}, {offset}, {width}){cast_out}",
                        address.code
                    ),
                    result,
                );
            }
            AtomicKind::Store => {
                let mut values = self.pop_n(2)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                let call = self.write_call("atomic_store");
                self.line(&format!(
                    "self.memory.{call}{}, {offset}, {width}, {}{cast_in});",
                    values[0].code, values[1].code
                ));
            }
            AtomicKind::Rmw(kind) => {
                let mut values = self.pop_n(2)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                let call = self.write_call("atomic_rmw");
                self.push_temp(
                    &format!(
                        "self.memory.{call}{}, {offset}, {width}, rt::Rmw::{}, {}{cast_in}){cast_out}",
                        values[0].code,
                        kind.rt_name(),
                        values[1].code
                    ),
                    result,
                );
            }
            AtomicKind::Cmpxchg => {
                let mut values = self.pop_n(3)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                let call = self.write_call("atomic_cmpxchg");
                self.push_temp(
                    &format!(
                        "self.memory.{call}{}, {offset}, {width}, {}{cast_in}, {}{cast_in}){cast_out}",
                        values[0].code, values[1].code, values[2].code
                    ),
                    result,
                );
            }
            AtomicKind::Notify => {
                let mut values = self.pop_n(2)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                // The count decides the program: three threads on a lock and
                // `notify(addr, 1)` means one of them proceeds.
                self.push_temp(
                    &format!(
                        "self.memory.atomic_notify_count({}, {offset}, {})",
                        values[0].code, values[1].code
                    ),
                    ValType::I32,
                );
            }
            AtomicKind::Wait => {
                let mut values = self.pop_n(3)?;
                self.spill_operands(&mut values);
                // Nothing folded reads memory, so a memory write invalidates nothing.
                self.push_temp(
                    &format!(
                        "self.memory.atomic_wait({}, {offset}, {width}, {}{cast_in}, {})",
                        values[0].code, values[1].code, values[2].code
                    ),
                    ValType::I32,
                );
            }
        }
        Ok(())
    }

    fn emit_num(&mut self, num: NumOp) -> Result<()> {
        let operands = self.pop_n(num.operands().len())?;
        let code = ops::render(
            num.template(),
            &operands.iter().map(Value::as_operand).collect::<Vec<_>>(),
        );
        // Everything that can trap is spelled as a call into the runtime, so
        // the template says whether this is safe to fold.
        if num.template().starts_with("rt::") {
            self.push_temp(&code, num.result());
        } else {
            let reads = operands
                .iter()
                .fold(Reads::default(), |all, operand| all.and(operand.reads));
            self.push_pure(&code, num.result(), reads);
        }
        Ok(())
    }

    fn emit_call(&mut self, index: u32) -> Result<()> {
        let ty = self
            .module
            .func_type(index)
            .ok_or_else(|| {
                Error::invalid(
                    format!("call to unknown function #{index}"),
                    self.location(),
                )
            })?
            .clone();
        let mut arguments = self.pop_n(ty.params.len())?;
        self.spill_operands(&mut arguments);
        self.spill_across_a_call();
        let call = format!(
            "self.{}({})",
            function_ident_with(index, self.analysis, self.recognised),
            arguments
                .iter()
                .map(|value| value.code.clone())
                .collect::<Vec<_>>()
                .join(", ")
        );
        match ty.results.first() {
            None => self.line(&format!("{call};")),
            Some(result) => self.push_temp(&call, *result),
        }
        Ok(())
    }

    fn emit_call_indirect(&mut self, type_index: u32) -> Result<()> {
        let ty = self
            .module
            .types
            .get(type_index as usize)
            .ok_or_else(|| Error::invalid("call_indirect names a missing type", self.location()))?
            .clone();
        let index = self.pop()?;
        let mut arguments = self.pop_n(ty.params.len())?;
        let mut index = [index];
        self.spill_operands(&mut index);
        self.spill_operands(&mut arguments);
        self.spill_across_a_call();
        let mut parts = vec![index[0].code.clone()];
        parts.extend(arguments.iter().map(|value| value.code.clone()));
        let call = format!("self.call_indirect_{type_index}({})", parts.join(", "));
        match ty.results.first() {
            None => self.line(&format!("{call};")),
            Some(result) => self.push_temp(&call, *result),
        }
        Ok(())
    }

    fn emit_else(&mut self) -> Result<()> {
        let frame = self
            .frames
            .last()
            .ok_or_else(|| Error::invalid("`else` outside a block", self.location()))?;
        if frame.kind != FrameKind::If {
            return Err(Error::invalid(
                "`else` closing a non-if block",
                self.location(),
            ));
        }
        let label = frame.label;
        let result = frame.result;
        let height = frame.stack_height;

        // The consequent's result, if it produced one and could reach here.
        if !self.unreachable && result.is_some() {
            let value = self.pop()?;
            self.line(&format!("r{label} = {};", value.code));
        }
        self.stack.truncate(height);
        self.depth -= 1;
        self.line("} else {");
        self.depth += 1;
        self.unreachable = false;
        self.skipping = 0;
        if let Some(frame) = self.frames.last_mut() {
            frame.in_else = true;
            frame.unreachable = false;
        }
        Ok(())
    }

    fn emit_end(&mut self) -> Result<()> {
        let frame = self
            .frames
            .pop()
            .ok_or_else(|| Error::invalid("`end` with no open block", self.location()))?;

        if !self.unreachable && frame.result.is_some() {
            let value = self.pop()?;
            self.line(&format!("r{} = {};", frame.label, value.code));
        }
        self.stack.truncate(frame.stack_height);
        self.depth -= 1;

        match frame.kind {
            FrameKind::Block => self.line("}"),
            // A wasm loop falls out of the bottom; a Rust one repeats, so the
            // fallthrough is spelled out.
            FrameKind::Loop => {
                self.depth += 1;
                self.line("break;");
                self.depth -= 1;
                self.line("}");
            }
            FrameKind::If => self.line("} }"),
        }

        // Control reaches past the frame if the frame could be left by a branch,
        // even when its body ended unreachable. An `if` without an `else` can
        // always fall through the missing branch.
        self.unreachable = false;
        self.skipping = 0;
        if let Some(result) = frame.result {
            self.push(format!("r{}", frame.label), result, false, Reads::default());
        }
        Ok(())
    }

    /// The Rust name for a wasm local.
    ///
    /// The one local worth a real name is the frame base: `frame` says what it
    /// is, where `l3` says only where it was. Everything else keeps its index,
    /// because the index is what a `local.get 3` in the bytes refers to and a
    /// reader tracing one should not have to translate.
    fn local_ident(&self, index: u32) -> String {
        match self.frame {
            Some(frame) if frame.base_local == index => "frame".to_string(),
            _ => format!("l{index}"),
        }
    }

    fn local_type(&self, index: u32) -> Result<ValType> {
        let at = index as usize;
        if let Some(param) = self.ty.params.get(at) {
            return Ok(*param);
        }
        self.func
            .locals
            .get(at - self.ty.params.len())
            .copied()
            .ok_or_else(|| {
                Error::invalid(format!("local #{index} does not exist"), self.location())
            })
    }

    fn global_type(&self, index: u32) -> Result<ValType> {
        self.module
            .globals
            .get(index as usize)
            .map(|global| global.ty)
            .ok_or_else(|| {
                Error::invalid(format!("global #{index} does not exist"), self.location())
            })
    }
}

fn load_method(kind: LoadKind) -> &'static str {
    match kind {
        LoadKind::I32 => "load32",
        LoadKind::I64 => "load64",
        LoadKind::F32 => "load_f32",
        LoadKind::F64 => "load_f64",
        LoadKind::I32Load8S => "load8_s",
        LoadKind::I32Load8U => "load8_u",
        LoadKind::I32Load16S => "load16_s",
        LoadKind::I32Load16U => "load16_u",
        // The i64 narrow loads read the same bytes and widen to i64, which the
        // `as i64` in `load_cast` supplies.
        LoadKind::I64Load8S => "load8_s_i64",
        LoadKind::I64Load8U => "load8_u_i64",
        LoadKind::I64Load16S => "load16_s_i64",
        LoadKind::I64Load16U => "load16_u_i64",
        LoadKind::I64Load32S => "load32_s_i64",
        LoadKind::I64Load32U => "load32_u_i64",
    }
}

/// The runtime method for a store, and the cast its value needs.
///
/// The integer stores all take an `i64` and truncate, so an `i32` value widens
/// and an `i64` one does not. Widening an `i64` would compile and read as if
/// something were being converted.
fn store_method(kind: StoreKind) -> (&'static str, &'static str) {
    match kind {
        StoreKind::I32 => ("store32", " as i64"),
        StoreKind::I64 => ("store64", ""),
        StoreKind::F32 => ("store_f32", ""),
        StoreKind::F64 => ("store_f64", ""),
        StoreKind::I32Store8 => ("store8", " as i64"),
        StoreKind::I32Store16 => ("store16", " as i64"),
        StoreKind::I64Store8 => ("store8", ""),
        StoreKind::I64Store16 => ("store16", ""),
        StoreKind::I64Store32 => ("store32", ""),
    }
}

/// The Rust name of a function.
///
/// The index always leads: `f4213`, and `f4213_parse_xmpp_offer` when a name
/// could be guessed from the module's own log messages. Keeping the index is
/// what makes the guess safe to make — a reader tracing `call 4213` in the
/// bytes finds it either way, and a wrong guess costs a misleading suffix
/// rather than a lost thread.
#[must_use]
pub fn function_ident(index: u32, analysis: &Analysis) -> String {
    match analysis.derived_names.get(&index) {
        Some(derived) => format!("f{index}_{}", sanitize(&derived.name)),
        None => format!("f{index}"),
    }
}

/// As [`function_ident`], with a name a signature catalogue recognised.
fn function_ident_with(
    index: u32,
    analysis: &Analysis,
    recognised: &std::collections::BTreeMap<u32, String>,
) -> String {
    match recognised.get(&index) {
        Some(name) => format!("f{index}_{}", sanitize(name)),
        None => function_ident(index, analysis),
    }
}

/// The method name each exported function gets, in module order.
///
/// Public because anything that calls into generated code — a test harness, a
/// driver, a person — needs the same answer the backend used. Deriving it twice
/// is how a harness ends up calling a method that was never emitted.
#[must_use]
pub fn exported_functions(module: &Module) -> Vec<(&crate::module::Export, String)> {
    let mut used: BTreeSet<String> = BTreeSet::new();
    let mut out = Vec::new();
    for export in &module.exports {
        if export.kind != ExportKind::Func {
            continue;
        }
        let mut name = sanitize(&export.name);
        // Two exports can sanitise onto the same identifier — `loop` becomes
        // `loop_`, and so does `loop_`. The later one moves.
        while !used.insert(name.clone()) {
            name = format!("{name}_{}", export.index);
        }
        out.push((export, name));
    }
    out
}

/// The doc comment describing a function's stack frame.
///
/// The frame is the part of a C function that wasm cannot show directly: its
/// locals live in linear memory, addressed off a base the prologue reserves.
/// Naming the slots does not recover the variables, but it does say how many
/// there are, how wide, and which are read before they are written.
fn frame_summary(frame: &StackFrame) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "    ///");
    let _ = writeln!(
        out,
        "    /// Stack frame: {} bytes, based at `frame`{}.",
        frame.size,
        if frame.publishes {
            ", published to the stack pointer"
        } else {
            // Worth saying: it is how a leaf function is spelled.
            ", not published (nothing is called while it is live)"
        }
    );
    if frame.escapes {
        // Saying this plainly matters: the slots below are what could be
        // followed, not what is there.
        let _ = writeln!(
            out,
            "    /// The address leaves this function, so the slots below are only\n    /// the accesses this analysis could follow — not the whole frame."
        );
    }
    let outside = frame.writes_outside();
    if !outside.is_empty() {
        // The one thing in this summary that is a finding rather than a
        // description. A store past the end of the frame lands in the caller's,
        // and nothing else in the output would say so.
        let _ = writeln!(
            out,
            "    /// **Writes outside its own frame**: {}. A store at or past\n    /// {} bytes lands in the caller's frame.",
            outside
                .iter()
                .map(|(offset, width)| format!("`frame + {offset}` ({width} bytes)"))
                .collect::<Vec<_>>()
                .join(", "),
            frame.size
        );
    }
    if frame.computed_writes > 0 {
        let _ = writeln!(
            out,
            "    /// {} write{} go through an address computed from the frame at run\n    /// time — an indexed array. Whether they stay inside {} bytes is not\n    /// something this can say.",
            frame.computed_writes,
            if frame.computed_writes == 1 { "" } else { "s" },
            frame.size
        );
    }
    if frame.slots.is_empty() {
        let _ = writeln!(out, "    /// No slot accesses were resolved.");
        return out;
    }
    let _ = writeln!(out, "    ///");
    let _ = writeln!(out, "    /// | offset | width | reads | writes |");
    let _ = writeln!(out, "    /// |--------|-------|-------|--------|");
    for (offset, slot) in &frame.slots {
        let _ = writeln!(
            out,
            "    /// | +{offset} | {}B | {} | {} |",
            slot.width, slot.reads, slot.writes
        );
    }
    out
}

/// The field name a global gets.
///
/// Indices stay in the name — `g0_stack_pointer`, not `stack_pointer` — because
/// the index is what every other view of the module uses, and a reader tracing
/// a `global.get 0` should not have to work out which field that became.
fn global_ident(index: u32, analysis: &Analysis) -> String {
    match analysis.stack_pointer {
        Some(found) if found.global == index => format!("g{index}_stack_pointer"),
        _ => format!("g{index}"),
    }
}

/// Makes text safe to sit inside a `/* */` comment.
///
/// A string containing `*/` would otherwise close the comment early and the
/// output would not compile — which, for this project, is the one unacceptable
/// outcome. Newlines and tabs are escaped for the same reason a one-line
/// comment wants to stay on one line.
fn escape_comment(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '*' => out.push('∗'),
            '/' => out.push('∕'),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '"' => out.push('\''),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

/// A signature as the comments print it: `(i32,i32) -> ()`.
#[must_use]
pub fn signature_text(ty: &crate::module::FuncType) -> String {
    let params: Vec<&str> = ty.params.iter().map(|param| param.rust_name()).collect();
    let results: Vec<&str> = ty.results.iter().map(|result| result.rust_name()).collect();
    format!("({}) -> ({})", params.join(","), results.join(","))
}

fn signature_of(ty: &crate::module::FuncType) -> String {
    let mut signature = String::new();
    for (at, param) in ty.params.iter().enumerate() {
        let _ = write!(signature, ", p{at}: {}", param.rust_name());
    }
    signature
}

fn return_type(ty: &crate::module::FuncType) -> String {
    match ty.results.first() {
        None => String::new(),
        Some(result) => format!("-> {}", result.rust_name()),
    }
}

fn const_expr_literal(expr: ConstExpr) -> String {
    match expr {
        ConstExpr::I32(value) => format_i32(value),
        ConstExpr::I64(value) => format_i64(value),
        ConstExpr::F32(value) => format_f32(value),
        ConstExpr::F64(value) => format_f64(value),
        // An initialiser reading another global can only read an imported one,
        // which this level refuses at parse time; nothing else can reach here.
        ConstExpr::GlobalGet(index) => format!("/* global.get {index} */ 0"),
    }
}

/// `i32::MIN` has no negative literal in Rust: `-2147483648` is parsed as a
/// negation of a literal that does not fit.
fn format_i32(value: i32) -> String {
    if value == i32::MIN {
        "i32::MIN".to_string()
    } else {
        format!("{value}i32")
    }
}

fn format_i64(value: i64) -> String {
    if value == i64::MIN {
        "i64::MIN".to_string()
    } else {
        format!("{value}i64")
    }
}

/// Floats are written by their bits. A decimal literal would be a rounding of
/// the module's constant, and NaN and the infinities have no literal at all.
fn format_f32(value: f32) -> String {
    format!("f32::from_bits(0x{:08x}u32)", value.to_bits())
}

fn format_f64(value: f64) -> String {
    format!("f64::from_bits(0x{:016x}u64)", value.to_bits())
}

/// Turns an exported name into a Rust identifier.
///
/// Minified modules export names like `a`, `$`, and single non-ASCII
/// characters. The mapping only has to be legal and stable; the original is
/// recorded in the doc comment above the wrapper.
fn sanitize(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    for (at, ch) in name.chars().enumerate() {
        let usable = ch.is_ascii_alphanumeric() || ch == '_';
        if usable && !(at == 0 && ch.is_ascii_digit()) {
            out.push(ch);
        } else if usable {
            out.push('_');
            out.push(ch);
        } else {
            let _ = write!(out, "_{:x}", ch as u32);
        }
    }
    if out.is_empty() {
        out.push_str("_empty");
    }
    if is_rust_keyword(&out) {
        out.push('_');
    }
    out
}

/// The trait method an import becomes. Both halves are sanitised, so
/// `wasi_snapshot_preview1::fd_write` and a minified `a::b` both land on
/// something legal and readable.
fn import_ident(module: &str, field: &str) -> String {
    format!("{}_{}", sanitize(module), sanitize(field))
}

fn is_rust_keyword(name: &str) -> bool {
    const KEYWORDS: &[&str] = &[
        "as", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false",
        "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
        "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "type",
        "unsafe", "use", "where", "while", "async", "await", "box", "final", "macro", "override",
        "priv", "try", "typeof", "unsized", "virtual", "yield", "abstract", "become", "do",
    ];
    KEYWORDS.contains(&name)
}

/// Keeps a module's own text from closing the doc comment it is quoted in.
fn escape_doc(text: &str) -> String {
    text.replace('\\', "\\\\").replace('`', "'")
}

